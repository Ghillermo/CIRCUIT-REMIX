def arm_code(base, L, prev, note=False, v2=False, stereo=False, multi=False, ui=False, menu2=False, env=False, noblink=False):
    nwx = NW_X + (1 if v2 else 0)
    nk, nwg = NK + (1 if stereo else 0), NW_G + (1 if stereo else 0)           # (stereo, RH47) value 12 = the spread (Shift + K2)
    bip = BIP_UI if ui else BIP
    mul = MUL[:11] + (0,) if env else MUL                                  # (env, RH54: the engine's gate always 0, the envelope gates; envpage)
    tdef, tmul, toff, tidx, tbip = ((DEF + (0,), mul + (128,), OFFS + (0,), IDX + (G.P_SPRD,), bip + (0,)) if stereo else
                                    (DEF, mul, OFFS, IDX, bip))
    a = Asm(base)
    E = a.emit
    zc = [0]

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_g{zc[0]}"
        E(b_cond, n, INV[cond])
        E(b, target)
        a.label(n)

    t_def = base
    E(raw, b"".join(v.to_bytes(2, "little") for v in tdef))
    t_mul = t_def + 2 * nk
    E(raw, bytes(tmul) + bytes(toff) + bytes(tidx) + bytes(tbip))
    t_off, t_idx, t_bip = t_mul + nk, t_mul + 2 * nk, t_mul + 3 * nk
    E(raw, bytes((-(2 * nk + 4 * nk)) % 4))                              # (the code half-word aligned after the tables)

    # ---- c_gpst() -> r0 = our state (rhstate), 0 without our RAM; clobbers r1-r3
    a.label("c_gpst")
    E(push_list, [4], lr=True)
    E(bl, L["c_rst"])
    E(cmp_imm, 0, 0)
    E(b_cond, "gs_x", "eq")
    E(adds_imm8, 0, O_ST)
    a.label("gs_x")
    E(pop_list, [4], pc=True)

    # ---- c_gpblk() -> r0 = our block in the record's tail, 0 without the record; clobbers r1-r3
    a.label("c_gpblk")
    E(push_list, [4], lr=True)
    E(bl, L["c_rrt"])
    E(cmp_imm, 0, 0)
    E(b_cond, "gb_x", "eq")
    E(movw, 1, BLK)
    E(adds_reg, 0, 0, 1)
    a.label("gb_x")
    E(pop_list, [4], pc=True)

    # ---- c_gpsum(r0 = block) -> r0 = its check byte (bytes 3 .. BLK_LEN - 1); clobbers r1-r3
    a.label("c_gpsum")
    E(adds_imm8, 0, 3)
    E(movs_imm, 1, BLK_LEN - 3)
    E(movs_imm, 2, CHECK)
    a.label("gu_l")
    E(ldrb_imm, 3, 0, 0)
    E(eors_reg, 2, 3)
    E(adds_imm8, 0, 1)
    E(subs_imm8, 1, 1)
    E(b_cond, "gu_l", "ne")
    E(mov_reg, 0, 2)
    E(raw, h(0x4770))

    # ---- c_gpb() -> r0 = our block when it holds our values, else 0; clobbers r1-r3
    a.label("c_gpb")
    E(push_list, [4], lr=True)
    E(bl, "c_gpblk")
    E(cmp_imm, 0, 0)
    E(b_cond, "gk_x", "eq")
    E(mov_reg, 4, 0)
    E(ldrb_imm, 1, 4, 0)
    E(cmp_imm, 1, MARK0)
    E(b_cond, "gk_0", "ne")
    E(ldrb_imm, 1, 4, 1)
    E(cmp_imm, 1, MARK1)
    E(b_cond, "gk_0", "ne")
    E(bl, "c_gpsum")
    E(ldrb_imm, 1, 4, 2)
    E(cmp_reg, 0, 1)
    E(b_cond, "gk_0", "ne")
    E(mov_reg, 0, 4)
    E(pop_list, [4], pc=True)
    a.label("gk_0")
    E(movs_imm, 0, 0)
    a.label("gk_x")
    E(pop_list, [4], pc=True)

    # ---- c_gpfix(r0 = block): its check byte again; clobbers r0-r3
    a.label("c_gpfix")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, "c_gpsum")
    E(strb_imm, 0, 4, 2)
    E(pop_list, [4], pc=True)

    # ---- c_gpinit() -> r0 = our block, made with the defaults if missing (0 without the record); clobbers r1-r3
    a.label("c_gpinit")
    E(push_list, [4, 5, 6], lr=True)
    E(bl, "c_gpb")
    E(cmp_imm, 0, 0)
    E(b_cond, "gi_x", "ne")
    E(bl, "c_gpblk")
    E(cmp_imm, 0, 0)
    E(b_cond, "gi_x", "eq")
    E(mov_reg, 4, 0)
    E(movs_imm, 0, MARK0)
    E(strb_imm, 0, 4, 0)
    E(movs_imm, 0, MARK1)
    E(strb_imm, 0, 4, 1)
    E(movs_imm, 0, 0)
    E(strb_imm, 0, 4, 3)
    E(strb_imm, 0, 4, 4)
    E(strb_imm, 0, 4, 5)
    E(movs_imm, 5, 0)
    a.label("gi_l")
    imm32(0, t_def)
    E(lsls_imm, 1, 5, 1)
    E(adds_reg, 0, 0, 1)
    E(ldrh_imm, 0, 0, 0)
    E(adds_reg, 1, 4, 1)
    E(strh_imm, 0, 1, 6)
    E(adds_imm8, 5, 1)
    E(cmp_imm, 5, nk)
    E(b_cond, "gi_l", "lo")
    E(mov_reg, 0, 4)
    E(bl, "c_gpfix")
    E(mov_reg, 0, 4)
    a.label("gi_x")
    E(pop_list, [4, 5, 6], pc=True)

    if multi:
        _gn_funcs(a, E, imm32, L, nk, t_def, t_mul, t_off, t_idx, note)
    # ---- c_gpval(r0 = k) -> r0 = its value (the default without our block); clobbers r1-r3
    a.label("c_gpval" if not multi else "c_gpval1")
    E(push_list, [4, 5], lr=True)
    E(mov_reg, 5, 0)
    E(bl, "c_gpb")
    E(lsls_imm, 1, 5, 1)
    E(cmp_imm, 0, 0)
    E(b_cond, "gv_d", "eq")
    E(adds_reg, 0, 0, 1)
    E(ldrh_imm, 0, 0, 6)
    E(pop_list, [4, 5], pc=True)
    a.label("gv_d")
    imm32(0, t_def)
    E(adds_reg, 0, 0, 1)
    E(ldrh_imm, 0, 0, 0)
    E(pop_list, [4, 5], pc=True)

    # ---- c_gpput(r0 = k, r1 = value); clobbers r0-r3
    a.label("c_gpput" if not multi else "c_gpput1")
    E(push_list, [4, 5, 6], lr=True)
    E(mov_reg, 5, 0)
    E(mov_reg, 6, 1)
    E(bl, "c_gpinit")
    E(cmp_imm, 0, 0)
    E(b_cond, "gp_x", "eq")
    E(mov_reg, 4, 0)
    E(lsls_imm, 1, 5, 1)
    E(adds_reg, 1, 4, 1)
    E(strh_imm, 6, 1, 6)
