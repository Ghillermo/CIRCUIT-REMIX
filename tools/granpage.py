    if v2:                                                                # (v2: the bit = off; and pad 23 of Sample Rec over all)
        E(eors_reg, 0, 1)
        E(push_list, [0, 1])
        E(bl, "c_gpmflags")
        E(lsls_imm, 1, 0, 31)
        E(pop_list, [0, 1])
        E(b_cond, "gx_on", "pl")
        E(movs_imm, 0, 0)
        a.label("gx_on")
    E(movw, 1, XF.XFON)
    E(adds_reg, 1, 1, 4)
    E(b, "gx_w")
    a.label("gx_n")
    E(b_cond, "gx_q", "ne")
    E(movw, 0, XN)
    E(movw, 1, XF.XN)
    E(b, "gx_w")
    a.label("gx_q")
    if v2:
        E(cmp_imm, 4, 9)
        E(b_cond, "gx_9", "eq")
        E(bl, "c_gpmflags")                                               # word 10: stereorec's request
        E(lsrs_imm, 0, 0, 1)
        E(movs_imm, 1, 1)
        E(raw, h(0x4008))                                                 # ands r0, r1
        E(movw, 1, STQ)
        E(b, "gx_w")
        a.label("gx_9")
    E(movw, 0, XQ)
    E(movw, 1, XF.XQ)
    a.label("gx_w")
    E(movs_imm, 2, 1)
    E(bl, "c_gpw")
    E(pop_list, [4], pc=True)

    if v2:
        # ---- c_gpmst() -> r0 = our menu state (OFF2), 0 without our RAM; c_gpmflags() -> r0 = its flags (0 without); clobber r1-r3
        a.label("c_gpmst")
        E(push_list, [4], lr=True)
        E(bl, L["c_rram"])
        E(cmp_imm, 0, 0)
        E(b_cond, "ms_x", "eq")
        E(movw, 1, MN_O)
        E(adds_reg, 0, 0, 1)
        a.label("ms_x")
        E(pop_list, [4], pc=True)
        a.label("c_gpmflags")
        E(push_list, [4], lr=True)
        E(bl, "c_gpmst")
        E(cmp_imm, 0, 0)
        E(b_cond, "mf_x", "eq")
        E(ldrb_imm, 0, 0, M_FLAGS)
        a.label("mf_x")
        E(pop_list, [4], pc=True)

        # ---- c_gpgran(r0 = track) -> r0 = 1 on its Granular page (its page bit and the engine on it); clobbers r1-r3
        a.label("c_gpgran")
