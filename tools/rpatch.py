def demo_data(slot):
    """(demos) a demo slot's engine and its RX data bytes 4 .. RX_N - 1 (FM: its instrument)"""
    import synthpage as SY
    if slot < 8:
        _, kn, ef, start, mode, det, ext, slope = DEMO_VA[slot]
        if SY.ratio2() and slot in DEMO_R2:                                # (RH85, ratio2) OSC 2 as a ratio: the demo re-voiced
            kn = tuple(DEMO_R2[slot].get(k, v) for k, v in enumerate(kn))
        d = SY.va_raw_bytes(kn, raw14=ef, raw15=start) + bytes([mode + 1, det]) + bytes(x ^ 64 for x in ext) + bytes([slope, 0])
        return ES.E_VA, d
    if slot < 16:
        return ES.E_FM, DEMO_FM[slot - 8]
    _, vals, env = DEMO_GR[slot - 16]
    return ES.E_GR, bytes(vals) + bytes(env)


def demo_slot(slot):
    """(demos) what c_rpget gives for an empty demo slot: its padding and FM record (the tests')"""
    import fm8inst as I
    eng, d = demo_data(slot)
    if eng == ES.E_FM:
        return bytes([0xFF]) * PAD_LEN, V.record(I.inst_full(d))
    return model_rx(eng, d), bytes([0xFF]) * FM_LEN


def demo_table():
    out = bytearray()
    for sl in list(range(8)) + list(range(16, 24)):
        eng, d = demo_data(sl)
        e = bytearray(32)
        e[0] = eng
        e[4:4 + len(d)] = d
        out += e
    return bytes(out) + bytes(DEMO_FM)


def nib_cols():
    """nibble (engine + 1; 0 empty, 15 foreign) -> (bright, dim)"""
    t = [(COL_EMPTY, COL_EMPTY)] + [(0, 0)] * 15
    t[ES.E_VA + 1], t[ES.E_GR + 1], t[ES.E_FM + 1] = HC.GREEN, HC.MAGENTA, HC.VIOLET
    return t


def model_rx(eng, data):
    """our part of a slot (172 bytes) for the engine and its data bytes (the tests')"""
    r = bytearray(b"\xFF" * PAD_LEN)
    r[0:3] = bytes((ord("R"), ord("X"), eng))
    r[4:RX_N] = bytes(data[:RX_N - 4]).ljust(RX_N - 4, b"\0")
    c = CHECK0
    for x in r[4:RX_N]:
        c ^= x
    r[3] = c
    return bytes(r)


def model_nib(pad, fm):
    """a slot's kind from its padding and FM record (the ARM's c_rpcls)"""
    if pad[0:2] == b"RX" and pad[2] in (ES.E_VA, ES.E_GR, ES.E_FM):
        c = CHECK0
        for x in pad[4:RX_N]:
            c ^= x
        if c == pad[3]:
            return pad[2] + 1
    if fm[0:4] == V.REC_HDR:
        return ES.E_FM + 1
    if pad[0:4] == b"CTM1":
        return N_FOREIGN
    return N_EMPTY


def pad_slot(page, pad):
    """the slot of a pad of the list (None: not a slot)"""
    if 16 <= pad < 24:
        return None
    i = pad if pad < 16 else pad - 8
    s = page * PER_PAGE + i
    return s if s < NSLOT else None


def arm_code(base, L, prev):
    import rhbuild
    a = Asm(base)
    E = a.emit
    zc = [0]

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_r{zc[0]}"
        E(b_cond, n, INV[cond])
        E(b, target)
        a.label(n)

    def popw(regs, lr=False):
        return h(0xE8BD) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0))

    import tabpack as TBP
    TB2 = TBP.v2()                                                        # (RH91, tabpack2: the tables in the ITCM; the patch lists only)
    data = bytearray()
    for bright, dim in nib_cols():
        data += bytes((bright, dim))
    o_ff = len(data)
    data += bytes([0xFF] * 4)
    DEMOS = rhbuild.OPT.get("demos")
    ST = starters()                                                       # (RH87) the held engines' starters, pad 8's list
    PCL = pclr()                                                          # (RH90) the chosen presets
    if DEMOS:
        o_demo = len(data)
        data += demo_table()
        while len(data) % 4:
            data.append(0)
    tb = TBP.region("rpatch_t", [(bytes(data), 1)]) if TB2 else base
    t_col, t_ff = tb, tb + o_ff
    if DEMOS:
        t_demo = tb + o_demo
        t_fmi = t_demo + 16 * 32
    if not TB2:
        E(raw, bytes(data))

    # ---- c_rpram() -> r0 = our RAM (from zero once); clobbers r1-r3
    a.label("c_rpram")
    imm32(0, PTR)
    E(ldr_imm, 1, 0, O_MAG)
    imm32(2, MAG)
    E(cmp_reg, 1, 2)
    E(b_cond, "rr_x", "eq")
    E(movs_imm, 1, 0)
    E(movs_imm, 3, PTR_LEN)
    a.label("rr_z")
    E(subs_imm8, 3, 4)
    E(raw, h(0x50C1))                                                     # str r1, [r0, r3]
    E(b_cond, "rr_z", "ne")
    E(str_imm, 2, 0, O_MAG)
    a.label("rr_x")
    E(raw, h(0x4770))

    # ---- c_rpcur() -> r0 = the loaded pack's number (as sesscopy's c_sccur); clobbers r1-r3
    a.label("c_rpcur")
    E(push_list, [3, 4], lr=True)
    imm32(4, SC.PACKS_VIEW)
    E(ldr_imm, 0, 4, 0)
    imm32(1, SC.PACKS_VT)
    E(cmp_reg, 0, 1)
    E(b_cond, "cu_ff", "ne")
    E(ldr_imm, 0, 4, 0x10)
    E(movs_imm, 1, 0)
    E(bl, CI.PARAM_NEW)
    E(ldr_imm, 0, 0, 0)
    E(b, "cu_b")
    a.label("cu_ff")
    imm32(0, SC.CUR_PACK_PTR)
    E(ldr_imm, 0, 0, 0)
    E(ldrb_imm, 0, 0, 0)
    a.label("cu_b")
    E(lsls_imm, 0, 0, 24)
    E(lsrs_imm, 0, 0, 24)
    E(pop_list, [3, 4], pc=True)

    # ---- c_rpnib(r0 = slot) -> r0 = its kind; c_rpsetn(r0 = slot, r1 = kind); clobber r0-r3
    a.label("c_rpnib")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, "c_rpram")
    E(lsrs_imm, 1, 4, 1)
    E(adds_reg, 0, 0, 1)
    E(ldrb_w, 0, 0, O_NIB)
    E(lsls_imm, 1, 4, 31)
    E(b_cond, "nb_l", "eq")
    E(lsrs_imm, 0, 0, 4)
    a.label("nb_l")
    E(movs_imm, 1, 15)
    E(raw, h(0x4008))                                                     # ands r0, r1
    E(pop_list, [4], pc=True)
    a.label("c_rpsetn")
    E(push_list, [4, 5], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(bl, "c_rpram")
    E(lsrs_imm, 1, 4, 1)
    E(adds_reg, 0, 0, 1)
    E(ldrb_w, 1, 0, O_NIB)
    E(movs_imm, 2, 15)
    E(lsls_imm, 3, 4, 31)
    E(b_cond, "sn_l", "eq")
    E(lsls_imm, 2, 2, 4)
    E(lsls_imm, 5, 5, 4)
    a.label("sn_l")
    E(bics_reg, 1, 2)
    E(orrs_reg, 1, 5)
    E(strb_w, 1, 0, O_NIB)
    E(pop_list, [4, 5], pc=True)

    # ---- c_rpio(r0 = 0 read / 1 write, r1 = offset, r2 = bytes, r3 = buffer; [sp] = the bank, [sp + 4] = the pack) -> r0 = 0 when every
    #      byte went; clobbers r0-r3 (projsnd's c_psio with a buffer)
    a.label("c_rpio")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(ldr_sp, 4, 20)
    E(ldr_sp, 5, 24)
    E(sub_sp_imm, 32)
    E(mov_reg, 7, 13)
    E(mov_reg, 6, 2)                                                      # r6 = the bytes
    E(movs_imm, 2, 0)
    E(str_imm, 2, 7, 0)
    E(str_imm, 2, 7, 4)
    E(str_imm, 2, 7, 12)
    E(mov_reg, 2, 7)
    E(adds_imm8, 2, 12)
    E(str_imm, 2, 7, 8)
    E(movs_imm, 2, PS.KIND_BANK)
    E(str_imm, 2, 7, 16)
    E(str_imm, 4, 7, 20)
    E(strb_imm, 5, 7, 24)
    E(mov_reg, 4, 0)                                                      # r4 = the operation
    E(mov_reg, 2, 3)
    E(mov_reg, 3, 6)
    E(mov_reg, 0, 7)
    E(adds_imm8, 0, 16)
    E(cmp_imm, 4, 0)
    E(b_cond, "io_w", "ne")
    E(bl, PS.READ)
    E(b, "io_r")
    a.label("io_w")
    E(bl, PS.WRITE)
    a.label("io_r")
    E(cmp_imm, 0, 0)
    E(b_cond, "io_x", "ne")
    E(cmp_imm, 4, 0)
    E(b_cond, "io_x", "ne")
    E(ldr_imm, 0, 7, 12)
    E(subs_reg, 0, 0, 6)
    a.label("io_x")
    E(add_sp_imm, 32)
    E(pop_list, [4, 5, 6, 7], pc=True)

    # ---- rio(op, offset reg, bytes reg/imm, buffer) helpers inline: push the bank / pack, call, drop them
    def io(op, off_reg, nbytes, buf_reg, bank_reg, pack_reg):
        E(push_list, [pack_reg])
        E(push_list, [bank_reg])
        if off_reg != 1:
            E(mov_reg, 1, off_reg)
        if isinstance(nbytes, str):
            E(mov_reg, 2, int(nbytes[1:]))
        else:
            E(movw, 2, nbytes)
        if buf_reg != 3:
            E(mov_reg, 3, buf_reg)
        E(movs_imm, 0, op)
        E(bl, "c_rpio")
        E(add_sp_imm, 8)

    # ---- c_rpfill(r0 = address, r1 = bytes (x 4), r2 = word); clobbers r1
    a.label("c_rpfill")
    a.label("fl_l")
    E(subs_imm8, 1, 4)
    E(raw, h(0x5042))                                                     # str r2, [r0, r1]
    E(b_cond, "fl_l", "ne")
    E(raw, h(0x4770))

    # ---- c_rpfm(r0 = a slot in the buffer) -> r0 = 1 when its FM record is there ("FM8" 1); clobbers r1, r2
    a.label("c_rpfm")
    E(movw, 1, PAD_LEN)
    E(adds_reg, 0, 0, 1)
    E(ldr_imm, 0, 0, 0)
    imm32(1, int.from_bytes(V.REC_HDR, "little"))
    E(cmp_reg, 0, 1)
    E(b_cond, "fm_n", "ne")
    E(movs_imm, 0, 1)
    E(raw, h(0x4770))
    a.label("fm_n")
    E(movs_imm, 0, 0)
    E(raw, h(0x4770))

    # ---- c_rpcls(r0 = a padding, r1 = 1 its FM record there) -> r0 = the kind (model_nib); clobbers r1-r3
    a.label("c_rpcls")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(ldrb_imm, 0, 4, 0)
    E(cmp_imm, 0, ord("R"))
    E(b_cond, "cl_f", "ne")
    E(ldrb_imm, 0, 4, 1)
    E(cmp_imm, 0, ord("X"))
    E(b_cond, "cl_f", "ne")
    E(movs_imm, 0, CHECK0)
    E(movs_imm, 2, 4)
    a.label("cl_k")
    E(ldrb_reg, 3, 4, 2)
    E(eors_reg, 0, 3)
    E(adds_imm8, 2, 1)
    E(cmp_imm, 2, RX_N)
    E(b_cond, "cl_k", "lo")
    E(ldrb_imm, 2, 4, 3)
    E(cmp_reg, 0, 2)
    E(b_cond, "cl_f", "ne")
    E(ldrb_imm, 0, 4, 2)
    for e in (ES.E_VA, ES.E_GR, ES.E_FM):
        E(cmp_imm, 0, e)
        E(b_cond, "cl_e", "eq")
    a.label("cl_f")
    E(movs_imm, 0, ES.E_FM + 1)
    E(cmp_imm, 1, 0)
    E(b_cond, "cl_x", "ne")
    E(ldr_imm, 0, 4, 0)
    imm32(1, int.from_bytes(b"CTM1", "little"))
    E(cmp_reg, 0, 1)
    E(b_cond, "cl_n", "ne")
    E(movs_imm, 0, N_FOREIGN)
