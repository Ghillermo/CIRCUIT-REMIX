def ldrsh_reg(rt, rn, rm): return h(0x5E00 | rm << 6 | rn << 3 | rt)
def asrs_imm(rd, rm, n): return h(0x1000 | n << 6 | rm << 3 | rd)


def model_pos(pos):
    """a knob's position -> (destination, amount 1..16), None when off"""
    return None if pos == 0 else ((pos - 1) >> 4, ((pos - 1) & 15) + 1)


def model_bits(tb, bit, width):
    w = tb[bit >> 3] | tb[(bit >> 3) + 1] << 8
    return (w >> (bit & 7)) & ((1 << width) - 1)


def model_lfo(shape, ph, sh=0):
    p = ph >> 16
    if shape == 0:
        return (p if p < 0x8000 else 0xFFFF - p) - ONE
    if shape == 1:
        return (p >> 1) - ONE
    if shape == 2:
        return ONE if p < 0x8000 else -ONE
    return (sh - 128) << 7


def model_inc(r):
    """the phase's advance a ms, a free rate r = 16..31"""
    x = 2 * (r - 16) + 1
    return (4 + (x & 3)) << (15 + (x >> 2))


def model_sync(r, tick):
    """the phase of a rate r = 0..15 to the tempo"""
    d = DIVS[r]
    return ((tick % d) << 16) // d << 16


def model_ms(d):
    return (4 + (d & 3)) << (2 + (d >> 2))


def model_ramp(a_, b_, span):
    """the values of a ramp, micro step by micro step, the end not included"""
    return [a_ + int((b_ - a_) * i / span) for i in range(span)]


def arm_code(base, L, prev):
    import rhbuild
    XL = rhbuild.OPT.get("mxx", False)
    a = Asm(base)
    E = a.emit
    zc = [0]

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_m{zc[0]}"
        E(b_cond, n, SP.INV[cond])
        E(b, target)
        a.label(n)

    t_pbr = bytes((0x01, SP.UI_KNOB, GP.UI_KNOB, SY.UI_KNOB, EV.COL))
    t_pdm = bytes((0x09, SP.UI_DIM, GP.UI_DIM, SY.UI_DIM, EV.DIM))
    t_cls = bytes((0x01, SP.UI_KNOB, GP.UI_KNOB, SY.UI_KNOB, 0, 0))
    H = lambda vs: b"".join(struct.pack("<H", v) for v in vs)             # noqa: E731
    tabs = t_pbr + t_pdm + t_cls + bytes(PAR_KNOB) + bytes(PAR_MAX) + bytes(PAR_DEF) + bytes(ZC_LFO) + bytes(ZC_ATK) + bytes(PSND)
    VA = SY.va()                                                          # (RH77, synthpage va) the VA's knobs: their bipolar ones, K1 / K3 the morph
    bipm = BIP_MASKS[:3] + (sum(1 << i for i, v in enumerate(SY.BIP_VA) if v),) if VA else BIP_MASKS
    tabs += H(ATK_MS) + H(DIVS) + H(bipm) + H(SP.UI_TYPES) + bytes(SY.UI_WAVES_VA if VA else SY.UI_WAVES)
    assert len(tabs) % 2 == 0 and len(tabs) == 102
    LL = rhbuild.OPT.get("leftlight")                                     # (RH78) bipolar knobs: the lighter shade left (kbright.BIPLEFT)
    if VA and LL:                                                         # (va) K7's zones' colours (synthpage.VA_ZONES)
        tabs += b"".join(struct.pack("<H", v) for v in SY.VA_ZONES + (0,))
    E(raw, tabs)
    T_VZ = base + 102
    T_PBR, T_PDM, T_CLS, T_PK, T_PM, T_PD, T_ZC, T_PS = base, base + 5, base + 10, base + 16, base + 24, base + 28, base + 32, base + 40
    T_ATK, T_DIV, T_BIP, T_TYP, T_WV = base + 44, base + 52, base + 84, base + 92, base + 98

    # ---- c_mxram() -> r0 = our RAM, 0 without; clobbers r1-r3
    a.label("c_mxram")
    E(push_list, [], lr=True)
    E(bl, L["c_rram"])
    E(cmp_imm, 0, 0)
    E(b_cond, "mr_x", "eq")
    E(movw, 1, O)
    E(adds_reg, 0, 0, 1)
    a.label("mr_x")
    E(pop_list, [], pc=True)

    # ---- c_mxro() -> r0 = the tracks' bytes of the block, 0 without its marker; clobbers r1-r3
    a.label("c_mxro")
    E(push_list, [], lr=True)
    E(bl, L["c_rrt"])
    E(cmp_imm, 0, 0)
    E(b_cond, "ro_x", "eq")
    E(movw, 1, BLK)
    E(adds_reg, 0, 0, 1)
    E(ldrb_imm, 1, 0, 0)
    E(cmp_imm, 1, ord("M"))
    E(b_cond, "ro_0", "ne")
    E(ldrb_imm, 1, 0, 1)
    E(cmp_imm, 1, ord("X"))
    E(b_cond, "ro_0", "ne")
    E(adds_imm8, 0, 4)
    E(pop_list, [], pc=True)
    a.label("ro_0")
    E(movs_imm, 0, 0)
    a.label("ro_x")
    E(pop_list, [], pc=True)

