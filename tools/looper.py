"""The looper / live sampler's controls (MIT; RD50; the user, 2026-11-11: «Pads 9 sample from input, 10 resample. Hold during length. Tap for
bar length. Shift: arm. Pads 11-14: tap: one shot. Hold: loop during the hold. Shift: toggle loop (sync to the beat)»; «Last one touched. Pad
held: overdub», the bar length «Set with a knob», arm = the next bar, overdub onto a playing loop; docs/DISENO_LOOPER.md).  The engine:
tools/looper0.py on core 0 (its control words in core 0's X, written with 0x08031200).

The Grid FX view (Shift + Mixer: the Mixer's mode 7; pads 9-14 do nothing in the stock, K1-K8 are the tracks' levels and Shift + a knob the
same as the knob):
  * pad 9 = record the line input, pad 10 = resample the mix (after the Grid FX, without the loops), into the loop of the last loop pad
    touched: held = while held; a tap (released before TAP ms) = N bars from its start (replace: the DSP stops at exactly that many frames;
    overdub: until N bars of the global tick have gone); Shift = armed: it starts at the next bar (stopped: at the first step after Play); a press while recording or armed = stop / cancel;
  * overdub (onto the loop as it plays: old x FB + new) when that loop pad is held or the loop is looping; else the recording replaces it;
  * pads 11-14 = the loops 1-4 (each pick its loop): tap = one shot from the start; held past TAP = it loops until let go; Shift = loop
    at the tempo on / off (it starts at the next beat; stopped: at once); Clear + pad = the loop emptied;
  * Shift + K8 = N (the user, 2026-11-11: 1/2, 1, 2, 4 bars, only in this view; a mode knob: 32 clicks a length, K8's LED in its
    length's colour, COL_N);
  * LEDs: 9 / 10 dim red, bright red recording from that source, amber armed; 11-14 dark empty, dim amber with audio, medium amber picked,
    bright amber playing.
Bars and beats: the global tick (p0 of [SEQ + 0x90], 24 a quarter note) crossing a bar (96) or a beat (24), seen at each step start (the
players' slot 4, player 0) and in each LED frame.  The DSP's heads are followed one a frame (c_d16r: a one shot stops there).
RAM: LPR (fxseq's room + 96): see the O_* offsets.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from thumb import (Asm, adds_imm8, adds_reg, ands_reg, b, b_cond, b_w, bics_reg, bl, cmp_imm, cmp_reg, h, ldr_imm, ldr_sp, ldrb_imm,  # noqa: E402
                   lsls_imm, lsls_reg, lsrs_imm, lsrs_reg, mov_reg, movs_imm, movt, movw, muls, orrs_reg, pop_list, push_list, raw,
                   str_imm, strb_imm, subs_imm8, subs_reg, tst_reg, ldrb_w, strb_w)
import countin as CI  # noqa: E402
import granpage as GP  # noqa: E402
import looper0 as L0  # noqa: E402
import fxseq as FX  # noqa: E402

LPR = FX.FXR + 96
MAG = 0x504F4F4C                                          # "LOOP"
(O_MAG, O_SEL, O_ACT, O_RPAD, O_NB, O_HELD, O_HLOOP, O_BPEND, O_CONT, O_SH, O_TAP, O_INIT, O_SRC, O_OVD, O_POLL, O_RH, O_NV,  # bytes
 O_RT, O_PT, O_STOP, O_LBAR, O_LBEAT, LP_LEN) = (0, 4, 5, 6, 7, 8, 9, 10, 11, 12, 16, 17, 18, 19, 20, 21, 22, 24, 28, 44, 48, 52, 56)
COL_N = (0xBB, 0x89, 0x8E, 0xA7)                          # Shift + K8's lengths: 1/2 bar yellow, 1 orange, 2 red-orange, 4 salmon
TAP = 300
LEVEL = 0x7FFFFF                                          # each loop's playback level (set up once; no control for it yet)
FB = 0x666666                                             # the overdub's feedback (0.8)
TPB, TPQ = 96, 24                                         # global ticks a bar / a beat
FRAMES_BAR = 4 * 60 * 48000                               # frames a bar x BPM
INIT_N = 8 * 4 + 8                                        # the control words zeroed (heads 4 x 8, the recording 8), then the key
P_REC, P_LOOP = 8, 10                                     # pads 9 / 10, 11-14 (indexes)
COL_RED, COL_REDD = 0x53, 0x54
COL_A, COL_AM, COL_AD = 0x85, 0xE1, 0x95                  # amber: bright, medium, dim (unused codes, not animated)
HAL = CI.HAL_TICK
SEQ, TRANSPORT, TEMPO = 0x2003C380, 0x200122B0, 0x20012788
CLEAR_BIT = 1 << 23
INV = dict(eq="ne", ne="eq", lo="hs", hs="lo", hi="ls", ls="hi", ge="lt", lt="ge", gt="le", le="gt", mi="pl", pl="mi")


def popw(regs, lr=False): return h(0xE8BD) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0))
def udiv(rd, rn, rm): return h(0xFBB0 | rn) + h(0xF0F0 | rd << 8 | rm)


def arm_code(base, L, prev):
    a = Asm(base)
    E = a.emit
    zc = [0]

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_l{zc[0]}"
        E(b_cond, n, INV[cond])
        E(b, target)
        a.label(n)

    # ---- c_lpr() -> r0 = our RAM (zeroed once: MAG); clobbers r1-r3
    a.label("c_lpr")
    imm32(0, LPR)
    E(ldr_imm, 1, 0, O_MAG)
    imm32(2, MAG)
    E(cmp_reg, 1, 2)
    E(b_cond, "lr_x", "eq")
    E(movs_imm, 1, 0)
    E(movs_imm, 3, LP_LEN)
    a.label("lr_z")
    E(subs_imm8, 3, 4)
    E(raw, h(0x50C1))                                                     # str r1, [r0, r3]
    E(b_cond, "lr_z", "ne")
    E(str_imm, 2, 0, O_MAG)
    a.label("lr_x")
    E(raw, h(0x4770))

    # ---- c_lpw(r0 = core 0 X address, r1 = value): written; clobbers r0-r3
    a.label("c_lpw")
    E(push_list, [4], lr=True)
    E(mov_reg, 2, 0)
    E(lsls_imm, 1, 1, 8)
    E(movs_imm, 0, 0)
    E(bl, L["WR16"])
    E(pop_list, [4], pc=True)

    # ---- c_lphw(r0 = head, r1 = field, r2 = value): a head's control word; clobbers r0-r3
    a.label("c_lphw")
    E(lsls_imm, 0, 0, 3)
    E(adds_reg, 0, 0, 1)
    imm32(1, L0.HD)
    E(adds_reg, 0, 0, 1)
    E(mov_reg, 1, 2)
    E(b, "c_lpw")

    # ---- c_lprw(r0 = field, r1 = value): the recording's control word; clobbers r0-r3
    a.label("c_lprw")
    imm32(2, L0.RC)
    E(adds_reg, 0, 0, 2)
    E(b, "c_lpw")

    # ---- c_lpok() -> r0 = 1 when the stock is up, core 0 holds the mode 0 program and our control words are set up; clobbers r1-r3
    a.label("c_lpok")
    E(push_list, [4], lr=True)
    E(bl, L["c_ciok"])
    E(cmp_imm, 0, 0)
    E(b_cond, "ok_0", "eq")
    E(bl, L["c_rst"])
    E(cmp_imm, 0, 0)
    E(b_cond, "ok_0", "eq")
    E(ldrb_w, 1, 0, L["O_TH"])
    E(cmp_imm, 1, L["READY"])
    E(b_cond, "ok_0", "ne")
    E(bl, "c_lpr")
    E(ldrb_imm, 1, 0, O_INIT)
    E(cmp_imm, 1, INIT_N + 1)
    E(b_cond, "ok_0", "lo")
    E(movs_imm, 0, 1)
    E(pop_list, [4], pc=True)
    a.label("ok_0")
    E(movs_imm, 0, 0)
    E(pop_list, [4], pc=True)

    # ---- c_lpgrid() -> r0 = 1 with the Grid FX view on the screen; clobbers r1-r3
    a.label("c_lpgrid")
    E(push_list, [4], lr=True)
    imm32(0, CI.CTRL)
    E(ldr_imm, 0, 0, 0x7C)
    E(bl, L["c_fxmix"])
    E(pop_list, [4], pc=True)

    # ---- c_lptick() -> r0 = the global tick; c_lpplay() -> r0 = the transport running; clobbers r1-r3
    a.label("c_lptick")
    E(push_list, [4], lr=True)
    imm32(0, SEQ + 0x90)
    E(ldr_imm, 0, 0, 0)
    E(movs_imm, 1, 0)
    E(bl, CI.PARAM_NEW)
    E(ldr_imm, 0, 0, 0)
    E(pop_list, [4], pc=True)
    a.label("c_lpplay")
    E(push_list, [4], lr=True)
    imm32(0, TRANSPORT)
    E(movs_imm, 1, 0)
    E(bl, L["c_cinew"])
    E(pop_list, [4], pc=True)

    # ---- c_lpframes() -> r0 = N (half a bar << the index) in frames at the tempo (a multiple of 32, <= CAP); clobbers r1-r3
    a.label("c_lpframes")
    E(push_list, [4], lr=True)
    imm32(0, TEMPO)
    E(movs_imm, 1, 0)
    E(bl, L["c_cinew"])
    E(cmp_imm, 0, 20)
    E(b_cond, "fr_b", "hs")
    E(movs_imm, 0, 120)
    a.label("fr_b")
    E(mov_reg, 4, 0)                                                      # r4 = BPM
    E(bl, "c_lpr")
    E(ldrb_imm, 1, 0, O_NB)
    E(movs_imm, 0, 1)
    E(lsls_reg, 0, 1)                                                     # N = 1 << index
    imm32(1, FRAMES_BAR // 2)                                             # (N half bars)
    E(muls, 0, 1)
    E(raw, udiv(0, 0, 4))
    E(lsrs_imm, 0, 0, 5)
    E(lsls_imm, 0, 0, 5)
    imm32(1, L0.CAP)
    E(cmp_reg, 0, 1)
    E(b_cond, "fr_x", "ls")
    E(mov_reg, 0, 1)
    a.label("fr_x")
    E(pop_list, [4], pc=True)

    # ---- c_lpstart(r0 = the limit in frames): the recording on (its head, source and overdub from our RAM); clobbers r0-r3
    a.label("c_lpstart")
    E(push_list, [4, 5, 6], lr=True)
    E(mov_reg, 6, 0)
    E(bl, "c_lpr")
    E(mov_reg, 5, 0)
    E(ldrb_imm, 4, 5, O_SEL)                                              # r4 = the head
    E(strb_imm, 4, 5, O_RH)
    E(ldrb_imm, 0, 5, O_OVD)
    E(cmp_imm, 0, 0)
    E(b_cond, "st_ov", "ne")
    for fld in (0, 1, 2):                                                 # replace: the head stopped and emptied first
        E(mov_reg, 0, 4)
        E(movs_imm, 1, fld)
        E(movs_imm, 2, 0)
        E(bl, "c_lphw")
    E(adds_reg, 1, 5, 4)
    E(movs_imm, 0, 0)
    E(strb_imm, 0, 1, O_SH)
    E(movs_imm, 0, 5)
    E(movs_imm, 1, 0)
    E(bl, "c_lprw")
    E(b, "st_o")
    a.label("st_ov")                                                      # overdub: its loop looping (held: until let go)
    E(adds_reg, 0, 5, 4)
    E(ldrb_imm, 0, 0, O_SH)
    E(cmp_imm, 0, 2)
    E(b_cond, "st_o", "eq")
    E(mov_reg, 0, 4)
    E(movs_imm, 1, 2)
    E(bl, "c_lphead")
    E(ldrb_imm, 0, 5, O_HELD)
    E(lsrs_reg, 0, 4)
    E(movs_imm, 1, 1)
    E(ands_reg, 0, 1)
    E(lsls_reg, 0, 4)
    E(ldrb_imm, 1, 5, O_HLOOP)
    E(orrs_reg, 1, 0)
    E(strb_imm, 1, 5, O_HLOOP)
    a.label("st_o")
    E(movs_imm, 0, 1)
    E(mov_reg, 1, 4)
    E(bl, "c_lprw")
    E(movs_imm, 0, 2)
    E(ldrb_imm, 1, 5, O_SRC)
    E(bl, "c_lprw")
    E(movs_imm, 0, 3)
    E(ldrb_imm, 1, 5, O_OVD)
    E(bl, "c_lprw")
    E(movs_imm, 0, 4)
    imm32(1, FB)
    E(bl, "c_lprw")
    E(movs_imm, 0, 7)
    E(mov_reg, 1, 6)
    E(bl, "c_lprw")
    E(movs_imm, 0, 0)
    E(movs_imm, 1, 1)
    E(bl, "c_lprw")                                                       # on, the last
    E(movs_imm, 0, 1)
    E(strb_imm, 0, 5, O_ACT)
    E(ldrb_imm, 0, 5, O_CONT)
    E(movs_imm, 1, 1)
    E(lsls_reg, 1, 4)
    E(orrs_reg, 0, 1)
    E(strb_imm, 0, 5, O_CONT)
    E(pop_list, [4, 5, 6], pc=True)

    # ---- c_lpstop(): the recording off (or the armed one cancelled); clobbers r0-r3
    a.label("c_lpstop")
    E(push_list, [4], lr=True)
    E(movs_imm, 0, 0)
    E(movs_imm, 1, 0)
    E(bl, "c_lprw")
    E(bl, "c_lpr")
    E(movs_imm, 1, 0)
    E(strb_imm, 1, 0, O_ACT)
    E(str_imm, 1, 0, O_STOP)
    E(pop_list, [4], pc=True)

    # ---- c_lphead(r0 = head, r1 = state): a head started from frame 0 (1 once, 2 loop) or stopped (0); its shadow; clobbers r0-r3
    a.label("c_lphead")
    E(push_list, [4, 5], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(cmp_imm, 5, 0)
    E(b_cond, "hd_s", "eq")
    E(movs_imm, 1, 2)
    E(movs_imm, 2, 0)
    E(bl, "c_lphw")                                                       # its position 0 first
    E(mov_reg, 0, 4)
    a.label("hd_s")
    E(mov_reg, 0, 4)
    E(movs_imm, 1, 0)
    E(mov_reg, 2, 5)
    E(bl, "c_lphw")
    E(bl, "c_lpr")
    E(adds_reg, 1, 0, 4)
    E(strb_imm, 5, 1, O_SH)
    E(cmp_imm, 5, 0)
    E(b_cond, "hd_x", "ne")
    E(bl, "c_lpend")
    a.label("hd_x")
    E(pop_list, [4, 5], pc=True)

    # ---- c_lpend(r0 = our RAM, r4 = a head): the recording into it stopped (a head stopped or emptied); clobbers r0-r3
    a.label("c_lpend")
    E(ldrb_imm, 1, 0, O_ACT)
    E(cmp_imm, 1, 0)
    E(b_cond, "en_x", "eq")
    E(ldrb_imm, 1, 0, O_RH)
    E(cmp_reg, 1, 4)
    E(b_cond, "en_x", "ne")
    E(b, "c_lpstop")
    a.label("en_x")
    E(raw, h(0x4770))

    # ---- c_lptk(): bars and beats: a pending loop start at a beat, an armed recording at a bar, an overdub's tap at its end; clobbers r0-r3
    a.label("c_lptk")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(bl, "c_lpok")
    E(cmp_imm, 0, 0)
    bc("tk_x", "eq")
    E(bl, "c_lpplay")
    E(cmp_imm, 0, 0)
    bc("tk_x", "eq")
    E(bl, "c_lptick")
    E(mov_reg, 6, 0)                                                      # r6 = the tick
    E(bl, "c_lpr")
    E(mov_reg, 7, 0)                                                      # r7 = our RAM
    # a beat crossed: the pending loops start
    E(movs_imm, 1, TPQ)
    E(raw, udiv(4, 6, 1))                                                 # r4 = the beat
    E(ldr_imm, 0, 7, O_LBEAT)
    E(str_imm, 4, 7, O_LBEAT)
    E(cmp_reg, 0, 4)
    E(b_cond, "tk_bar", "eq")
    E(ldrb_imm, 5, 7, O_BPEND)
    E(movs_imm, 0, 0)
    E(strb_imm, 0, 7, O_BPEND)
    E(movs_imm, 4, 0)
    a.label("tk_h")
    E(mov_reg, 0, 5)
    E(lsrs_reg, 0, 4)
    E(movs_imm, 1, 1)
    E(tst_reg, 0, 1)
    E(b_cond, "tk_hn", "eq")
    E(mov_reg, 0, 4)
    E(movs_imm, 1, 2)
    E(bl, "c_lphead")
    a.label("tk_hn")
    E(adds_imm8, 4, 1)
    E(cmp_imm, 4, 4)
    E(b_cond, "tk_h", "lo")
    # a bar crossed: the armed recording starts
    a.label("tk_bar")
    E(movs_imm, 1, TPB)
    E(raw, udiv(4, 6, 1))                                                 # r4 = the bar
    E(ldr_imm, 0, 7, O_LBAR)
    E(str_imm, 4, 7, O_LBAR)
    E(cmp_reg, 0, 4)
    E(b_cond, "tk_end", "eq")
    E(ldrb_imm, 0, 7, O_ACT)
    E(cmp_imm, 0, 2)
    E(b_cond, "tk_end", "ne")
    imm32(0, L0.CAP)
    E(ldrb_imm, 1, 7, O_TAP)
    E(cmp_imm, 1, 0)
    E(b_cond, "tk_s", "eq")
    E(bl, "c_lpframes")                                                   # tapped while armed: N bars
    a.label("tk_s")
    E(bl, "c_lpstart")
    E(ldrb_imm, 0, 7, O_TAP)
    E(ldrb_imm, 1, 7, O_OVD)
    E(ands_reg, 0, 1)
    E(b_cond, "tk_end", "eq")                                             # an overdub tapped: until N bars of ticks
    E(bl, "c_lpnbt")
    E(adds_reg, 0, 0, 6)
    E(str_imm, 0, 7, O_STOP)
    # the overdub's end
    a.label("tk_end")
    E(ldr_imm, 0, 7, O_STOP)
    E(cmp_imm, 0, 0)
    E(b_cond, "tk_x", "eq")
    E(cmp_reg, 6, 0)
    E(b_cond, "tk_x", "lo")
    E(bl, "c_lpstop")
    a.label("tk_x")
    E(pop_list, [4, 5, 6, 7], pc=True)

    # ---- c_lpnbt() -> r0 = N (48 ticks << the index) in global ticks; clobbers r1
    a.label("c_lpnbt")
    imm32(0, LPR)
    E(ldrb_imm, 1, 0, O_NB)
    E(movs_imm, 0, TPB // 2)
    E(lsls_reg, 0, 1)
    E(raw, h(0x4770))

    # ---- c_lps4 (the players' slot 4, in front: r0 = player): player 0's steps run the bars and beats; then the chain
    a.label("c_lps4")
    E(push_list, [0, 1, 2, 3], lr=True)
    imm32(3, FX.PL0)
    E(cmp_reg, 0, 3)
    E(b_cond, "s4_p", "ne")
    E(bl, "c_lptk")
    a.label("s4_p")
    E(raw, popw([0, 1, 2, 3], lr=True))
    E(b_w, prev["s4"])

    # ---- c_lppad (the head of the pad press chain: r0 = ctrl, r1 = pad, r2 = velocity): pads 9-14 in the Grid FX view
    a.label("c_lppad")
    E(cmp_imm, 1, P_REC)
    bc("pp_p0", "lo")
    E(cmp_imm, 1, P_LOOP + 3)
    bc("pp_p0", "hi")
    E(push_list, [0, 1, 2, 4, 5, 6, 7], lr=True)
    E(mov_reg, 5, 1)                                                      # r5 = the pad
    E(bl, "c_lpok")
    E(cmp_imm, 0, 0)
    bc("pp_p", "eq")
    E(bl, "c_lpgrid")
    E(cmp_imm, 0, 0)
    bc("pp_p", "eq")
    E(bl, "c_lpr")
    E(mov_reg, 7, 0)                                                      # r7 = our RAM
    E(cmp_imm, 5, P_LOOP)
    bc("pp_lp", "hs")
    # pads 9 / 10: a press while recording or armed = stop
    E(ldrb_imm, 0, 7, O_ACT)
    E(cmp_imm, 0, 0)
    E(b_cond, "pp_r", "eq")
    E(bl, "c_lpstop")
    E(movs_imm, 0, 0xFF)
    E(strb_imm, 0, 7, O_RPAD)
    E(b, "pp_x")
    a.label("pp_r")
    E(mov_reg, 0, 5)
    E(subs_imm8, 0, P_REC)
    E(strb_imm, 0, 7, O_SRC)
    E(strb_imm, 5, 7, O_RPAD)
    E(movs_imm, 0, 0)
    E(strb_imm, 0, 7, O_TAP)
    E(str_imm, 0, 7, O_STOP)
    imm32(0, HAL)
    E(ldr_imm, 0, 0, 0)
    E(str_imm, 0, 7, O_RT)
    # overdub: the picked loop pad held, or that loop looping
    E(ldrb_imm, 4, 7, O_SEL)
    E(ldrb_imm, 0, 7, O_HELD)
    E(lsrs_reg, 0, 4)
    E(movs_imm, 1, 1)
    E(ands_reg, 0, 1)
    E(adds_reg, 1, 7, 4)
    E(ldrb_imm, 1, 1, O_SH)
    E(cmp_imm, 1, 2)
    E(b_cond, "pp_ov", "ne")
    E(movs_imm, 0, 1)
    a.label("pp_ov")
    E(ldrb_imm, 1, 7, O_CONT)
    E(lsrs_reg, 1, 4)
    E(ands_reg, 0, 1)
    E(strb_imm, 0, 7, O_OVD)
    E(bl, L["c_cishift"])
    E(cmp_imm, 0, 0)
    E(b_cond, "pp_now", "eq")
    E(bl, "c_lpplay")
    E(cmp_imm, 0, 0)
    E(b_cond, "pp_stop", "eq")
    E(bl, "c_lptick")                                                     # armed: the bar now = the last one seen (it starts on the next)
    E(movs_imm, 1, TPB)
    E(raw, udiv(0, 0, 1))
    E(b, "pp_arm")
    a.label("pp_stop")                                                    # (the user: «arm con transporte parado: comienza a grabar cuando
    E(movs_imm, 0, 0)                                                     #  arranque el transporte») no bar yet: the first step after Play
    E(subs_imm8, 0, 1)
    a.label("pp_arm")
    E(str_imm, 0, 7, O_LBAR)
    E(movs_imm, 0, 2)
    E(strb_imm, 0, 7, O_ACT)
    E(b, "pp_x")
    a.label("pp_now")
    imm32(0, L0.CAP)
    E(bl, "c_lpstart")
    E(b, "pp_x")
    # pads 11-14: the loops
    a.label("pp_lp")
    E(mov_reg, 4, 5)
    E(subs_imm8, 4, P_LOOP)                                               # r4 = the head
    E(strb_imm, 4, 7, O_SEL)
    E(movs_imm, 6, 1)
    E(lsls_reg, 6, 4)                                                     # r6 = its bit
    E(ldr_sp, 0, 0)
    E(raw, h(0xF8D0) + h(0x10A0))                                         # ldr.w r1, [r0, #0xa0]: the held buttons
