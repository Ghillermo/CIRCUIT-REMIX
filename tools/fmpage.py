O, O_LEN = rhstate.OFF2["fmpage"]
R_ON, R_PEND, R_ROUND, R_HOLD, R_SIG, R_CLR, R_SWAL, R_VAL = 0, 1, 2, 3, 4, 6, 8, 12
R_POLY, R_BORR, R_PSENT, R_PRND = 76, 77, 78, 79      # (RH72, OPT poly) the poly tracks (bit t), the borrowed slots (bit s), the flags sent, their round
SIG = 0x4D46                                          # "FM"
NSL, NV, NW = 4, 16, 4 * len(V.PARAMS) + len(V.GLOBALS) + 1              # 49 words a slot, the key last
assert R_VAL + NSL * NV <= O_LEN
PAD_VA, PAD_FM, PAD_VD = 10, 11, 12                   # Sample mode's pads 11 / 12 / 13 (0-based; RH72: 13 = poly)
SL = SY.SL                                            # a slot's bytes in synthpage's block: the track + 1, the 16 values (from + 2)
ST0 = 16                                              # the starters on pads 17-32
