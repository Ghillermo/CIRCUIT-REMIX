    E(cmp_imm, 0, 0)
    E(b_cond, "pl_x", "eq")
    E(movs_imm, 1, SL)
    E(muls, 1, 4)
    E(adds_reg, 1, 0, 1)
    E(movs_imm, 2, 0)
