# the state (ST3 + ...): bytes first (ldrb #imm <= 31), then words (ldr #imm <= 124)
S_MODE, S_OWNED, S_SHIFT, S_WAS, S_FRESH, S_HEAD, S_TAIL, S_KILL, S_SPORT, S_RUN, S_PULSE, S_BPM = range(4, 16)
S_SOUND, S_KILLAT = 16, 24                          # 8 bytes each
S_FRAMES, S_FRAME, S_INPUT, S_CLOCK = 32, 36, 40, 44
S_PADMOD, S_BTNMOD, S_PADEAT, S_BTNEAT = 48, 52, 56, 60
S_UI, S_TRANSPORT, S_PULSES, S_STARTS, S_STOPS = 64, 68, 72, 76, 80
S_FAKE = 84                                          # 5 words: + 0 dirty, + 16 the bytes
S_Q = 104                                            # 8 words
S_REPLY = 136                                        # 80 bytes
S_LEDS = 224                                         # 224 bytes
assert S_LEDS + 224 <= rhstate.SIZE3

INV = {"eq": "ne", "ne": "eq", "lo": "hs", "hs": "lo", "hi": "ls", "ls": "hi", "cc": "cs", "cs": "cc", "mi": "pl", "pl": "mi"}


def pushw(regs, lr=False): return h(0xE92D) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0))
def popw(regs, lr=False, pc=False): return h(0xE8BD) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0) | (1 << 15 if pc else 0))
def ldr_reg(rt, rn, rm): return h(0x5800 | rm << 6 | rn << 3 | rt)
def str_reg(rt, rn, rm): return h(0x5000 | rm << 6 | rn << 3 | rt)
def udiv(rd, rn, rm): return h(0xFBB0 | rn) + h(0xF0F0 | rd << 8 | rm)
def umull(lo, hi, rn, rm): return h(0xFBA0 | rn) + h(lo << 12 | hi << 8 | rm)
def ldrex(rt, rn): return h(0xE850 | rn) + h(rt << 12 | 0x0F00)
def strex(rd, rt, rn): return h(0xE840 | rn) + h(rt << 12 | rd << 8)
def mvns(rd, rm): return h(0x43C0 | rm << 3 | rd)


DSB_ISB = h(0xF3BF) + h(0x8F4F) + h(0xF3BF) + h(0x8F6F)


def crc32(data, skip=8):
    import zlib
    return zlib.crc32(bytes(data[:skip]) + b"\0\0\0\0" + bytes(data[skip + 4:])) & 0xFFFFFFFF


def arm_code(base, L):
    """The code, with the short branches that do not reach widened (cbz -> cmp + b<c>, b<c> -> b<!c> over a b)"""
    import re
    far = set()
    while True:
        try:
            return _arm_code(base, L, far)
        except AssertionError as ex:
            m = re.search(r"\((cbz|b_cond) at 0x[0-9a-f]+, operands \('(\w+)'", str(ex))
            new = {(m.group(1), m.group(2))} if m else set()
            m = re.search(r"branch out of range without a pool between \(0x[0-9a-f]+ -> (\w+)\)", str(ex))      # (thumb.COMPACT)
            if m:
                new = {("cbz", m.group(1)), ("b_cond", m.group(1))}
            if not new or new <= far:
                raise
            far |= new


def _arm_code(base, L, far):
    a = Asm(base)
    n_skip = [0]

    def E(fn, *args, **kw):
        if fn is cbz and ("cbz", args[0]) in far:
            a.emit(cmp_imm, args[1], 0)
            fn, args, kw = b_cond, (args[0], "ne" if kw.get("nz") else "eq"), {}
        if fn is b_cond and ("b_cond", args[0]) in far:
            n_skip[0] += 1
            a.emit(b_cond, f"_sk{n_skip[0]}", INV[args[1]])
            a.emit(b, args[0])
            a.label(f"_sk{n_skip[0]}")
            return
        a.emit(fn, *args, **kw)

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def leds(rd, rs=4):                              # rd = the LED bytes of the state in rs
        E(movs_imm, rd, S_LEDS)
        E(adds_reg, rd, rd, rs)

    # ---- c_mhst -> r0 = the state, or 0 while rhstate's third block is not ours (claims nothing); clobbers r1, r2
    a.label("c_mhst")
    imm32(0, ST)
    imm32(1, rhstate.HEAP_LIMIT_PTR)
    E(ldr_imm, 1, 1, 0)
    E(cmp_reg, 1, 0)
    E(b_cond, "st_0", "ne")
    E(ldr_imm, 1, 0, 0)
    imm32(2, rhstate.MAGIC3)
    E(cmp_reg, 1, 2)
    E(b_cond, "st_x", "eq")
    a.label("st_0")
    E(movs_imm, 0, 0)
    a.label("st_x")
    E(raw, h(0x4770))

    # ---- c_mhok -> r0 = ITCM on and >= 16 KB; clobbers r1
    a.label("c_mhok")
    imm32(1, ITCMCR)
    E(ldr_imm, 0, 1, 0)
    E(lsrs_imm, 1, 0, 1)                             # C = EN
    E(b_cond, "ok_0", "cc")
    E(lsrs_imm, 0, 0, 3)
    E(movs_imm, 1, 15)
    E(ands_reg, 0, 1)
    E(cmp_imm, 0, 5)
    E(b_cond, "ok_0", "lo")
    E(movs_imm, 0, 1)
    E(raw, h(0x4770))
    a.label("ok_0")
    E(movs_imm, 0, 0)
    E(raw, h(0x4770))

    # ---- c_mhvalid(r0) -> r0 = r0 if a word-aligned SRAM address, else 0; clobbers r1
    a.label("c_mhvalid")
    E(lsls_imm, 1, 0, 30)
    E(b_cond, "va_0", "ne")
    imm32(1, 0x20000000)
    E(cmp_reg, 0, 1)
    E(b_cond, "va_0", "lo")
    imm32(1, 0x2004FFF0)
    E(cmp_reg, 0, 1)
    E(b_cond, "va_x", "lo")
    a.label("va_0")
    E(movs_imm, 0, 0)
    a.label("va_x")
    E(raw, h(0x4770))

    # ---- c_mhcrc(r0 = p, r1 = n) -> r0 = CRC-32 (zlib) with bytes 8..11 as zero
    a.label("c_mhcrc")
    E(push_list, [4, 5, 6], lr=True)
    E(movs_imm, 2, 0)
    E(raw, mvns(2, 2))
    imm32(4, 0xEDB88320)
    E(movs_imm, 3, 0)
    a.label("cr_l")
    E(cmp_reg, 3, 1)
    E(b_cond, "cr_x", "hs")
    E(ldrb_reg, 5, 0, 3)
    E(mov_reg, 6, 3)
    E(subs_imm8, 6, 8)
    E(cmp_imm, 6, 4)
    E(b_cond, "cr_k", "hs")
    E(movs_imm, 5, 0)
    a.label("cr_k")
    E(raw, h(0x4040 | 5 << 3 | 2))                   # eors r2, r5
    E(movs_imm, 6, 8)
    a.label("cr_b")
    E(lsrs_imm, 2, 2, 1)
    E(b_cond, "cr_n", "cc")
    E(raw, h(0x4040 | 4 << 3 | 2))                   # eors r2, r4
    a.label("cr_n")
    E(subs_imm8, 6, 1)
    E(b_cond, "cr_b", "ne")
    E(adds_imm8, 3, 1)
    E(b, "cr_l")
    a.label("cr_x")
    E(raw, mvns(0, 2))
    E(pop_list, [4, 5, 6], pc=True)

    # ---- c_mhchk -> r0 = 0 no module, 1 valid, 2 bad, 3 no ITCM
    a.label("c_mhchk")
    E(push_list, [4, 5, 6], lr=True)
    E(bl, "c_mhok")
    E(cbz, "ck_3", 0)
    E(movs_imm, 4, 1)
    E(lsls_imm, 4, 4, 10)                            # r4 = 0x400
    E(ldr_imm, 0, 4, 0)
    E(movs_imm, 6, 24)
    imm32(1, CRM1)
    E(cmp_reg, 0, 1)
    E(b_cond, "ck_h", "eq")
    E(movs_imm, 6, 28)
    imm32(1, CRM2)
    E(cmp_reg, 0, 1)
    E(b_cond, "ck_0", "ne")
    a.label("ck_h")
    E(ldr_imm, 5, 4, 4)                              # r5 = size, r6 = the header's length
    E(adds_imm3, 1, 6, 2)
    E(cmp_reg, 5, 1)
    E(b_cond, "ck_2", "lo")
    E(movw, 1, MOD_MAX)
    E(cmp_reg, 5, 1)
    E(b_cond, "ck_2", "hi")
    for off, zero in ((16, 0), (12, 1), (20, 1)):
        E(ldr_imm, 0, 4, off)
        E(movs_imm, 1, zero)
        E(bl, "mh_ent")
        E(cmp_imm, 0, 0)
        E(b_cond, "ck_2", "eq")
    E(cmp_imm, 6, 28)
    E(b_cond, "ck_c", "ne")
    E(ldr_imm, 0, 4, 24)
    E(movs_imm, 1, 1)
    E(bl, "mh_ent")
    E(cmp_imm, 0, 0)
    E(b_cond, "ck_2", "eq")
    a.label("ck_c")
    E(mov_reg, 0, 4)
    E(mov_reg, 1, 5)
    E(bl, "c_mhcrc")
    E(ldr_imm, 1, 4, 8)
    E(cmp_reg, 0, 1)
    E(b_cond, "ck_2", "ne")
    E(movs_imm, 0, 1)
    E(pop_list, [4, 5, 6], pc=True)
    a.label("ck_2")
    E(movs_imm, 0, 2)
    E(pop_list, [4, 5, 6], pc=True)
    a.label("ck_3")
    E(movs_imm, 0, 3)
    E(pop_list, [4, 5, 6], pc=True)
    a.label("ck_0")
    E(movs_imm, 0, 0)
    E(pop_list, [4, 5, 6], pc=True)
    # mh_ent(r0 = offset, r1 = 0 allowed; r5 = size, r6 = header) -> r0 = ok: bit 0, header <= offset - 1 <= size - 2
    a.label("mh_ent")
    E(cbz, "en_z", 0)
    E(lsrs_imm, 2, 0, 1)
    E(b_cond, "en_0", "cc")
    E(subs_imm8, 0, 1)
    E(cmp_reg, 0, 6)
    E(b_cond, "en_0", "lo")
    E(subs_imm3, 2, 5, 2)
    E(cmp_reg, 0, 2)
    E(b_cond, "en_0", "hi")
    E(movs_imm, 0, 1)
    E(raw, h(0x4770))
    a.label("en_z")
    E(mov_reg, 0, 1)
    E(raw, h(0x4770))
    a.label("en_0")
    E(movs_imm, 0, 0)
    E(raw, h(0x4770))

    # ---- c_mhret(r0 = s): retire (presses to tombstones, no owner, no clock, the ring flushed, every track released); clobbers r1-r3
    a.label("c_mhret")
    for mod, eat in ((S_PADMOD, S_PADEAT), (S_BTNMOD, S_BTNEAT)):
        E(ldr_imm, 1, 0, eat)
        E(ldr_imm, 2, 0, mod)
        E(orrs_reg, 1, 2)
        E(str_imm, 1, 0, eat)
    E(movs_imm, 1, 0)
    for f in (S_PADMOD, S_BTNMOD, S_CLOCK, S_PULSES):
        E(str_imm, 1, 0, f)
    E(strb_imm, 1, 0, S_OWNED)
    E(strb_imm, 1, 0, S_RUN)
    E(ldrb_imm, 2, 0, S_TAIL)
    E(strb_imm, 2, 0, S_HEAD)
    E(movs_imm, 3, 0xFF)
    E(strb_imm, 3, 0, S_KILL)
    a.label("re_l")
    E(adds_reg, 3, 0, 1)
    E(strb_imm, 2, 3, S_KILLAT)
    E(adds_imm8, 1, 1)
    E(cmp_imm, 1, 8)
    E(b_cond, "re_l", "ne")
    E(raw, h(0x4770))

    # ---- c_mhown(r0 = s) -> r0 = the module owns the controls; c_mhtin: it takes input (mode 3, frame, input); clobber r1
    a.label("c_mhown")
    E(ldrb_imm, 1, 0, S_OWNED)
    E(cbz, "ti_0", 1)
    a.label("c_mhtin")
    E(ldrb_imm, 1, 0, S_MODE)
    E(cmp_imm, 1, 3)
    E(b_cond, "ti_0", "ne")
    E(ldr_imm, 1, 0, S_FRAME)
    E(cbz, "ti_0", 1)
    E(ldr_imm, 1, 0, S_INPUT)
    E(cbz, "ti_0", 1)
    E(movs_imm, 0, 1)
    E(raw, h(0x4770))
    a.label("ti_0")
    E(movs_imm, 0, 0)
    E(raw, h(0x4770))

    # ---- c_mhstart(r0 = s; the scheduler suspended) -> r0 = runs: stop what ran, check, zero the module's RAM, init, its entries
    a.label("c_mhstart")
    E(push_list, [4, 5, 6], lr=True)
    E(mov_reg, 4, 0)
    E(bl, "c_mhret")
    E(movs_imm, 0, 0)
    E(strb_imm, 0, 4, S_MODE)
    E(str_imm, 0, 4, S_FRAME)
    E(str_imm, 0, 4, S_INPUT)
    E(ldrb_imm, 0, 4, S_FRESH)
    E(cbz, "sa_0", 0)
    E(bl, "c_mhchk")
    E(cmp_imm, 0, 1)
    E(b_cond, "sa_0", "ne")
    E(movs_imm, 0, 0)
    E(movs_imm, 1, 1)
    E(lsls_imm, 1, 1, 8)
    E(movs_imm, 5, 1)
    E(lsls_imm, 5, 5, 10)                            # r5 = 0x400
    a.label("sa_z")
    E(str_imm, 0, 1, 0)
    E(adds_imm8, 1, 4)
    E(cmp_reg, 1, 5)
    E(b_cond, "sa_z", "lo")
    E(raw, DSB_ISB)
    E(ldr_imm, 1, 5, 12)
    E(cbz, "sa_i", 1)
    E(adds_reg, 1, 1, 5)
    leds(0)
    E(blx_reg, 1)
    a.label("sa_i")
    E(ldr_imm, 0, 5, 16)
    E(adds_reg, 0, 0, 5)
    E(str_imm, 0, 4, S_FRAME)
    E(ldr_imm, 0, 5, 20)
    E(cbz, "sa_n", 0)
    E(adds_reg, 0, 0, 5)
    E(movs_imm, 1, 1)
    E(strb_imm, 1, 4, S_OWNED)                       # an input module owns the controls from its start
    a.label("sa_n")
    E(str_imm, 0, 4, S_INPUT)
    E(ldr_imm, 0, 5, 0)
    imm32(1, CRM2)
    E(cmp_reg, 0, 1)
    E(b_cond, "sa_c", "ne")
    E(ldr_imm, 0, 5, 24)
    E(cbz, "sa_c", 0)
    E(adds_reg, 0, 0, 5)
    E(str_imm, 0, 4, S_CLOCK)
    a.label("sa_c")
    E(movs_imm, 0, 3)
    E(strb_imm, 0, 4, S_MODE)
    E(movs_imm, 0, 1)
    E(pop_list, [4, 5, 6], pc=True)
    a.label("sa_0")
    E(movs_imm, 0, 0)
    E(pop_list, [4, 5, 6], pc=True)

    # ---- c_mhrun(r0 = s): frames + 1, one frame of the module; it returned 0 (or none): retired, mode 0
    a.label("c_mhrun")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(ldr_imm, 1, 4, S_FRAMES)
    E(adds_imm8, 1, 1)
    E(str_imm, 1, 4, S_FRAMES)
    E(ldr_imm, 2, 4, S_FRAME)
    E(cbz, "ru_s", 2)
    leds(0)
    E(blx_reg, 2)
    E(cmp_imm, 0, 0)
    E(b_cond, "ru_x", "ne")
    a.label("ru_s")
    E(mov_reg, 0, 4)
    E(bl, "c_mhret")
    E(movs_imm, 0, 0)
    E(str_imm, 0, 4, S_FRAME)
    E(strb_imm, 0, 4, S_MODE)
    a.label("ru_x")
    E(pop_list, [4], pc=True)

    # ---- c_mhfr (bl at 0x0802596E: frame, src, flag): the LED driver's frame
    a.label("c_mhfr")
    E(push_list, [3, 4, 5, 6, 7], lr=True)
    E(mov_reg, 5, 0)
    E(mov_reg, 6, 1)
    E(mov_reg, 7, 2)
    E(bl, "c_mhst")
    E(cbz, "fr_p", 0)
    E(mov_reg, 4, 0)
    E(bl, SUSPEND)
    E(ldrb_imm, 0, 4, S_MODE)
    E(cmp_imm, 0, 3)
    E(b_cond, "fr_n", "ne")
    E(ldr_imm, 0, 4, S_INPUT)
    E(cbz, "fr_s", 0)
    E(ldrb_imm, 0, 4, S_OWNED)
    E(cbz, "fr_u", 0)
    a.label("fr_s")                                   # shown: only on a frame the driver takes
    E(ldrb_imm, 0, 5, 2)
    E(cbz, "fr_r", 0)
    E(movs_imm, 0, 1)
    E(strb_imm, 0, 4, S_WAS)
