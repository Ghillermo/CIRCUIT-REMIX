CRM1, CRM2 = 0x314D5243, 0x324D5243
ITCMCR = 0xE000EF90
MOD_BASE, MOD_RAM, MOD_MAX = 0x400, 0x100, 0x3C00
ST = rhstate.ST3
SUSPEND, RESUME = 0x08024E04, 0x08024E14            # the scheduler's suspend-all / resume-all
SITES = dict(frame=(0x0802596E, 0x0802960C), main=(0x0802586C, 0x0802677A), pulse=(0x08033384, 0x080333AA), sysex=(0x08026E42, 0x0802CF90))
THUNKS = dict(pad=(0x080295CA, 0x08040108, 1), btn=(0x080295D8, 0x0804012A, 2), prs=(0x080295F0, 0x08040152, 4), enc=(0x080295FC, 0x0804015E, 5))
