SLOT, GUARD = 192, 256
CB = 0x2004F760                                   # the control block, above the heap's limit
O_MAGIC, O_ALIVE, O_PMAG, O_PEND, O_ST, O_RR, O_HRR, O_T0, O_REG = 0, 4, 8, 12, 13, 14, 15, 16, 20   # (O_T0: the boot's tick at the set-up)
O_TRK = O_REG + 8 * 12                            # 8 tracks x 12 B: + 0 pattern, + 1 step, + 2 flags (1 started, 2 length known), + 3 last step,
O_TAB = O_TRK + 8 * 12                            #   + 4 the step's start (ms), + 8 the step's length (ms)
MAGIC, PMAGIC, PEND_ON = 0x314E4C58, 0x444E5050, 0xC9   # "XLN1", "PPND"
NMAGIC = 0x57454E50                                     # (RH103, lnnew) "PNEW": the load in course is a new project
NEW_CALL, NEW_SESSION = 0x08038742, 0x08032DB2          # the project load 0x080386DC's «new session» call (an empty slot / a new project)
CANARY, CAN_MAGIC = 0x3380, 0x4C4E4341
K_STAB, K_VOL, K_BKP, K_STK = 0, 1, 2, 3
SETTINGS, P_SET2, MSC_BIT = 0x20012478, 2, 17
RCC_AHB1ENR, BKPSRAMEN, PWR_CR1, DBP = 0x40023830, 1 << 18, 0x40007000, 1 << 8
TCB_STACK = 48
TASKS = (("Main", 0x20007B9C, 0x2000879C), ("UI", 0x2000891C, 0x2000911C), ("Storage", 0x20009184, 0x20009684),
         ("Content", 0x200096F8, 0x20009BF8), ("IDLE", 0x2000B1BC, 0x2000B5BC))
STK_MAX = 6
RR_MAX, RAMP_MIN, DMIN, DMAX = 6, 32, 8, 4000
OFFL, STEPL, HEAD = 24576, 24576, 256
GAP_END = 24576                                        # (RH98, lngap) the end of projsnd's records: Hacks' 8 KB, the pack's patches, 8 x 2 KB
VER, CHECK0 = 1, 0xA5
CHUNK = 21                                         # lanes a 4 KB buffer
ST_OK, ST_WROTE, ST_NONE, ST_INT, ST_ERR = 0, 1, 2, 3, 4
TRANSPORT, HAL_TICK = CI.TRANSPORT, CI.HAL_TICK
STORE, P_LOADED = PS.STORE, PS.P_LOADED


def layout():
    """-> (regions [(start, most slots, kind, TCB)], NMAX, O_LAST, CB_END)"""
    low = [(0x100, (0x1780 - 0x100) // SLOT, K_STAB, 0), (0x1B98, (0x2000 - 0x1B98) // SLOT, K_STAB, 0)]
    rest = ([(0x2000, (CANARY - 0x2000) // SLOT, K_VOL, 0), (0x3C40, (0x4000 - 0x3C40) // SLOT, K_VOL, 0), (0x2004EC00, 2, K_VOL, 0)]
            + [(0x40024000, 4096 // SLOT, K_BKP, 0)] + [(base, STK_MAX, K_STK, tcb) for _, base, tcb in TASKS])
    n_fixed = sum(r[1] for r in low + rest)
    for above in range(8, -1, -1):                 # above the limit: as many slots as fit after the control block
        nmax = n_fixed + above
        o_last = O_TAB + 2 * nmax
        cb_end = (o_last + 2 * nmax + 31) & ~31
        if CB + cb_end + SLOT * above <= 0x2004FD00:
            break
    return low + [(CB + cb_end, above, K_STAB, 0)] + rest, nmax, o_last, cb_end


REGS, NMAX, O_LAST, CB_END = layout()
NREG = len(REGS)
assert O_TRK >= O_REG + 8 * NREG and NMAX <= (HEAD - 8) // 2 and NREG <= 32 and MX.XD_MAX < 64


def enc(v7):
    return (v7 * 125 >> 8) + 1


def dec14(v6):
    return (v6 - 1) * 264


def reg_table():
    return b"".join(struct.pack("<IBBHI", s, n, k, 0, t) for s, n, k, t in REGS)


NOES = [False]


def arm_code(base, L, prev):
    import rhbuild
    GAP = rhbuild.OPT.get("lngap")
    LNNEW = rhbuild.OPT.get("lnnew")                                      # (RH103) a new project does not read the slot's old lanes record
    a = Asm(base)
    E = a.emit
    zc = [0]
    RT = base                                                             # the regions' table, first

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        INV = {"eq": "ne", "ne": "eq", "lo": "hs", "hs": "lo", "hi": "ls", "ls": "hi", "lt": "ge", "ge": "lt", "gt": "le", "le": "gt",
               "mi": "pl", "pl": "mi", "cc": "cs", "cs": "cc"}
        zc[0] += 1
        n = f"_x{zc[0]}"
        E(b_cond, n, INV[cond])
        E(b, target)
        a.label(n)

    def ldr_reg(rt, rn, rm):
        E(raw, h(0x5800 | rm << 6 | rn << 3 | rt))

    def ldrh_r(rt, rn, rm):
        E(raw, h(0x5A00 | rm << 6 | rn << 3 | rt))

    def strh_r(rt, rn, rm):
        E(raw, h(0x5200 | rm << 6 | rn << 3 | rt))

    def sdiv(rd, rn, rm):
        E(raw, h(0xFB90 | rn) + h(0xF0F0 | rd << 8 | rm))

    def ret():
        E(raw, h(0x4770))

    def popw(regs, lr=False):
        E(raw, AR.popw(regs, lr=lr))

    E(raw, reg_table())

    # ---- c_lnram() -> r0 = CB when set up, else 0; clobbers r1, r2
    a.label("c_lnram")
    imm32(0, CB)
    E(ldr_imm, 1, 0, O_MAGIC)
    imm32(2, MAGIC)
    E(cmp_reg, 1, 2)
    E(b_cond, "lr_x", "eq")
    E(movs_imm, 0, 0)
    a.label("lr_x")
    ret()

    # ---- c_lnmsc() -> r0 = 1 when the stock's mass storage is off (the settings' bit 17); clobbers r0-r3
    a.label("c_lnmsc")
    E(push_list, [4], lr=True)
    imm32(0, SETTINGS)
    E(movs_imm, 1, P_SET2)
    E(bl, CI.PARAM_GET)
    E(ldr_imm, 0, 0, 0)
    E(lsrs_imm, 0, 0, MSC_BIT)
    E(movs_imm, 1, 1)
    E(ands_reg, 0, 1)
    E(pop_list, [4], pc=True)

    # ---- c_lnaddr(r0 = slot) -> r0 = its address (0: none / its region gone), r1 = its region; clobbers r2, r3
    a.label("c_lnaddr")
    E(push_list, [4, 5], lr=True)
    imm32(2, CB + O_REG)
    E(movs_imm, 3, 0)
    E(movs_imm, 4, 0)
    a.label("ad_l")
    E(cmp_imm, 3, NREG)
    E(b_cond, "ad_n", "hs")
    E(ldrb_imm, 5, 2, 4)
    E(adds_reg, 5, 5, 4)
    E(cmp_reg, 0, 5)
    E(b_cond, "ad_f", "lo")
    E(mov_reg, 4, 5)
    E(adds_imm8, 2, 8)
    E(adds_imm8, 3, 1)
    E(b, "ad_l")
    a.label("ad_f")
    imm32(5, CB)
    E(ldr_imm, 5, 5, O_ALIVE)
    E(lsrs_reg, 5, 3)
    E(lsls_imm, 5, 5, 31)
    E(b_cond, "ad_n", "pl")
    E(subs_reg, 0, 0, 4)
    E(movs_imm, 5, SLOT)
    E(muls, 0, 5)
    E(ldr_imm, 5, 2, 0)
    E(adds_reg, 0, 0, 5)
    E(mov_reg, 1, 3)
    E(pop_list, [4, 5], pc=True)
    a.label("ad_n")
    E(movs_imm, 0, 0)
    E(mov_reg, 1, 3)
    E(pop_list, [4, 5], pc=True)

    # ---- c_lnkill(r0 = region): gone, its lanes freed; clobbers r0-r3
    a.label("c_lnkill")
    E(push_list, [4, 5], lr=True)
    imm32(1, CB)
    E(ldr_imm, 2, 1, O_ALIVE)
    E(movs_imm, 3, 1)
    E(lsls_reg, 3, 0)
    E(bics_reg, 2, 3)
    E(str_imm, 2, 1, O_ALIVE)
    imm32(2, CB + O_REG)
    E(movs_imm, 4, 0)                                                     # r4 = the region's first slot
    E(movs_imm, 3, 0)
    a.label("kl_l")
    E(cmp_reg, 3, 0)
    E(b_cond, "kl_f", "eq")
    E(ldrb_imm, 5, 2, 4)
    E(adds_reg, 4, 4, 5)
    E(adds_imm8, 2, 8)
    E(adds_imm8, 3, 1)
    E(b, "kl_l")
    a.label("kl_f")
    E(ldrb_imm, 5, 2, 4)
    E(adds_reg, 5, 5, 4)                                                  # r5 = its end
    imm32(2, CB + O_TAB)
    E(movs_imm, 3, 0xFF)
    a.label("kl_s")
    E(cmp_reg, 4, 5)
    E(b_cond, "kl_x", "hs")
    E(lsls_imm, 1, 4, 1)
    E(strb_reg, 3, 2, 1)
    E(adds_imm8, 4, 1)
    E(b, "kl_s")
    a.label("kl_x")
    E(pop_list, [4, 5], pc=True)

    # ---- c_lnhealth(r0 = region) -> r0 = 1 usable now, else 0 (and gone); clobbers r0-r3
    a.label("c_lnhealth")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(mov_reg, 4, 0)
    imm32(5, CB + O_REG)
    E(lsls_imm, 0, 4, 3)
    E(adds_reg, 5, 5, 0)                                                  # r5 = its entry
    imm32(0, CB)
    E(ldr_imm, 0, 0, O_ALIVE)
    E(lsrs_reg, 0, 4)
    E(lsls_imm, 0, 0, 31)
    bc("he_0", "pl")
    E(ldrb_imm, 0, 5, 5)
    E(cmp_imm, 0, K_VOL)
    E(b_cond, "he_v", "eq")
    E(cmp_imm, 0, K_BKP)
    E(b_cond, "he_b", "eq")
    E(cmp_imm, 0, K_STK)
    E(b_cond, "he_s", "eq")
    a.label("he_1")
    E(movs_imm, 0, 1)
    E(pop_list, [4, 5, 6, 7], pc=True)
    a.label("he_v")                                                       # an upload since: every volatile region goes
    imm32(0, CANARY)
    E(ldr_imm, 0, 0, 0)
    imm32(1, CAN_MAGIC)
    E(cmp_reg, 0, 1)
    E(b_cond, "he_1", "eq")
    E(movs_imm, 6, 0)
    a.label("he_vl")
    imm32(5, CB + O_REG + 5)
    E(lsls_imm, 0, 6, 3)
    E(ldrb_reg, 0, 5, 0)
    E(cmp_imm, 0, K_VOL)
    E(b_cond, "he_vn", "ne")
    E(mov_reg, 0, 6)
    E(bl, "c_lnkill")
    a.label("he_vn")
    E(adds_imm8, 6, 1)
    E(cmp_imm, 6, NREG)
    E(b_cond, "he_vl", "lo")
    E(b, "he_0")
    a.label("he_b")
    if NOES[0]:                                                           # (RH97) Easy Start gone: nobody else uses it
        E(b, "he_1")
    else:
        E(bl, "c_lnmsc")
        E(cmp_imm, 0, 0)
        E(b_cond, "he_1", "ne")
        E(b, "he_k")
    a.label("he_s")
    E(ldr_imm, 6, 5, 0)                                                   # r6 = the base
    E(ldrb_imm, 0, 5, 4)
    E(movs_imm, 1, SLOT)
    E(muls, 0, 1)
    E(adds_reg, 6, 6, 0)                                                  # r6 = the slots' end
    imm32(0, GUARD)
    E(adds_reg, 7, 6, 0)                                                  # r7 = the guard's end
    E(mov_reg, 0, 6)
    a.label("he_g")
    E(ldrb_imm, 1, 0, 0)
    E(cmp_imm, 1, 0xA5)
    E(b_cond, "he_k", "ne")
    E(adds_imm8, 0, 1)
    E(cmp_reg, 0, 7)
    E(b_cond, "he_g", "lo")
    imm32(1, RT + 8)                                                      # the TCB, from the flash table
    E(movs_imm, 0, 12)
    E(muls, 0, 4)
    ldr_reg(1, 1, 0)
    E(ldr_imm, 2, 1, 0)                                                   # r2 = its saved top
    E(mov_reg, 0, 13)                                                     # sp: when it is the task that runs
    E(ldr_imm, 3, 5, 0)
    E(cmp_reg, 0, 3)
    E(b_cond, "he_t", "lo")
    E(cmp_reg, 0, 1)
    E(b_cond, "he_t", "hs")
    E(mov_reg, 2, 0)
    a.label("he_t")
    E(adds_imm8, 6, 64)
    E(cmp_reg, 2, 6)
    E(b_cond, "he_1", "hs")
    a.label("he_k")
    E(mov_reg, 0, 4)
    E(bl, "c_lnkill")
    a.label("he_0")
    E(movs_imm, 0, 0)
    E(pop_list, [4, 5, 6, 7], pc=True)

    # ---- c_lnwr(r0 = slot) -> r0 = its address when it may be written now, else 0; clobbers r0-r3
    a.label("c_lnwr")
    E(push_list, [4], lr=True)
    E(bl, "c_lnaddr")
    E(cmp_imm, 0, 0)
    E(b_cond, "wr_x", "eq")
    E(mov_reg, 4, 0)
    E(mov_reg, 0, 1)
    E(bl, "c_lnhealth")
    E(cmp_imm, 0, 0)
    E(b_cond, "wr_x", "eq")
    E(mov_reg, 0, 4)
    a.label("wr_x")
    E(pop_list, [4], pc=True)

    # ---- ln_bit(r1 = pattern, r2 = step) -> r2 = the byte, r3 = the shift; clobbers r1
    a.label("ln_bit")
    E(lsls_imm, 1, 1, 5)
    E(adds_reg, 1, 1, 2)
    E(lsls_imm, 2, 1, 2)
    E(lsls_imm, 1, 1, 1)
    E(adds_reg, 1, 1, 2)                                                  # 6 (32 p + s)
    E(lsrs_imm, 2, 1, 3)
    E(movs_imm, 3, 7)
    E(ands_reg, 3, 1)
    ret()

    # ---- c_lnget(r0 = slot, r1 = pattern, r2 = step) -> r0 = its value (0: none); clobbers r0-r3
    a.label("c_lnget")
    E(push_list, [1, 2, 4], lr=True)
    E(bl, "c_lnaddr")
    E(pop_list, [1, 2])
    E(cmp_imm, 0, 0)
    E(b_cond, "gt_x", "eq")
    E(mov_reg, 4, 0)
    E(bl, "ln_bit")
    E(adds_reg, 4, 4, 2)
    E(ldrb_imm, 0, 4, 0)
    E(cmp_imm, 3, 4)
    E(b_cond, "gt_1", "lo")
    E(ldrb_imm, 1, 4, 1)                                                  # (a field that crosses a byte: never past the lane's end)
    E(lsls_imm, 1, 1, 8)
    E(orrs_reg, 0, 1)
    a.label("gt_1")
    E(lsrs_reg, 0, 3)
    E(movs_imm, 1, 63)
    E(ands_reg, 0, 1)
    a.label("gt_x")
    E(pop_list, [4], pc=True)

    # ---- c_lnput(r0 = slot, r1 = pattern, r2 = step, r3 = value): written when it may be; clobbers r0-r3
    a.label("c_lnput")
    E(push_list, [1, 2, 3, 4, 5, 6], lr=True)
    E(bl, "c_lnwr")
    E(pop_list, [1, 2, 5])                                                # r5 = the value
    E(cmp_imm, 0, 0)
    E(b_cond, "pt_x", "eq")
    E(mov_reg, 4, 0)
    E(bl, "ln_bit")
    E(adds_reg, 4, 4, 2)                                                  # r4 = the byte
    E(ldrb_imm, 0, 4, 0)
    E(cmp_imm, 3, 4)
    E(b_cond, "pt_1", "lo")
    E(ldrb_imm, 1, 4, 1)
    E(lsls_imm, 1, 1, 8)
    E(orrs_reg, 0, 1)
    a.label("pt_1")
    E(movs_imm, 6, 63)
    E(lsls_reg, 6, 3)
    E(bics_reg, 0, 6)
    E(lsls_reg, 5, 3)
    E(orrs_reg, 0, 5)
    E(strb_imm, 0, 4, 0)
    E(cmp_imm, 3, 4)
    E(b_cond, "pt_x", "lo")
    E(lsrs_imm, 0, 0, 8)
    E(strb_imm, 0, 4, 1)
    a.label("pt_x")
    E(pop_list, [4, 5, 6], pc=True)

    # ---- c_lnfind(r0 = track, r1 = destination) -> r0 = its slot, -1 none; clobbers r0-r3
    a.label("c_lnfind")
    E(push_list, [4, 5], lr=True)
    imm32(2, CB + O_TAB)
    E(movs_imm, 3, 0)
    a.label("fd_l")
    E(lsls_imm, 4, 3, 1)
    E(ldrb_reg, 5, 2, 4)
    E(cmp_reg, 5, 0)
    E(b_cond, "fd_n", "ne")
    E(adds_imm8, 4, 1)
    E(ldrb_reg, 5, 2, 4)
    E(cmp_reg, 5, 1)
    E(b_cond, "fd_y", "eq")
    a.label("fd_n")
    E(adds_imm8, 3, 1)
    E(cmp_imm, 3, NMAX)
    E(b_cond, "fd_l", "lo")
    E(movs_imm, 0, 0)
    E(subs_imm8, 0, 1)
    E(pop_list, [4, 5], pc=True)
    a.label("fd_y")
    E(mov_reg, 0, 3)
    E(pop_list, [4, 5], pc=True)

    # ---- c_lnalloc(r0 = track, r1 = destination) -> r0 = a free slot, now its, zeroed; -1 none; clobbers r0-r3
    a.label("c_lnalloc")
    E(push_list, [4, 5, 6], lr=True)
    E(mov_reg, 5, 0)
    E(mov_reg, 6, 1)
    E(movs_imm, 4, 0)
    a.label("al_l")
    imm32(2, CB + O_TAB)
    E(lsls_imm, 1, 4, 1)
    E(ldrb_reg, 0, 2, 1)
    E(cmp_imm, 0, 0xFF)
    E(b_cond, "al_n", "ne")
    E(mov_reg, 0, 4)
    E(bl, "c_lnwr")
    E(cmp_imm, 0, 0)
    E(b_cond, "al_n", "eq")
    E(movs_imm, 1, 0)
    E(movs_imm, 2, SLOT)
    a.label("al_z")
    E(subs_imm8, 2, 1)
    E(strb_reg, 1, 0, 2)
    E(b_cond, "al_z", "ne")
    imm32(2, CB + O_TAB)
    E(lsls_imm, 1, 4, 1)
    E(adds_reg, 2, 2, 1)
    E(strb_imm, 5, 2, 0)
    E(strb_imm, 6, 2, 1)
    imm32(2, CB + O_LAST)
    E(movs_imm, 0, 0)
    strh_r(0, 2, 1)
    E(mov_reg, 0, 4)
    E(pop_list, [4, 5, 6], pc=True)
    a.label("al_n")
    E(adds_imm8, 4, 1)
