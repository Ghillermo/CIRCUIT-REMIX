    E(cmp_imm, 0, 0)
    E(b_cond, "gn_c", "eq")
    if stereo:                                                            # (stereo) Shift + K2: the spread, 128 a click
        E(cmp_imm, 5, 1)
        E(b_cond, "gn_f", "ne")
        E(movs_imm, 5, NK)
        E(b, "gn_c")
        a.label("gn_f")
    E(movs_imm, 7, FINE)                                                  # K1-K4: Shift = fine control
    E(b, "gn_c")
    a.label("gn_hi")
    E(cmp_imm, 0, 0)
    E(b_cond, "gn_c", "eq")
    E(adds_imm8, 5, 4)                                                    # Shift + K5-K8: the second layer (8..11)
    a.label("gn_c")
    E(bl, L["c_spheld"])
    E(lsls_imm, 0, 0, 31 - SP.BIT_CLEAR)
    E(b_cond, "gn_t", "pl")
    imm32(0, t_def)                                                       # Clear + the knob: its default
