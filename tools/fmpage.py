    E(strb_w, 2, 0, R_BORR)
    E(mov_reg, 0, 6)
    E(movs_imm, 1, 0)
    E(bl, "c_fmset")
    a.label("ps2_n")
    E(adds_imm8, 6, 1)
    E(cmp_imm, 6, NSL)
    bc("ps2_l", "lo")
    a.label("ps2_x")
    E(pop_list, [4, 5, 6], pc=True)
