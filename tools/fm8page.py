def kd():
    """the knobs' descriptors (param, max, clicks, kind) and defaults: [operator, pitch envelope] x 16 (8 plain, 8 with Shift)"""
    op = [(0, 35, 3, K_CMB), (V.O_FINE, 99, 1, K_OP), (V.O_OL, 99, 1, K_OP), (V.O_KVS, 7, 4, K_OP)] + [(V.O_R + i, 99, 1, K_OP) for i in range(4)]
    op += [(G + V.G_ALG, V.NALG - 1, 16, K_ABS), (G + V.G_FB, 127, 1, K_ABS), (V.O_RS, 7, 4, K_OP), (0, 99, 1, K_LS)]
    op += [(V.O_L + i, 99, 1, K_OP) for i in range(4)]
    pg = [(G + V.G_TRN, 48, 2, K_ABS), (0, 0, 1, K_NONE), (G + V.G_NZ, 127, 1, K_ABS), (G + V.G_NZOP, 7, 16, K_ABS)]
    pg += [(V.PEG + i, 99, 1, K_ABS) for i in range(4)]
    pg += [op[8], op[9], (0, 0, 1, K_NONE), (0, 0, 1, K_NONE)] + [(V.PEG + 4 + i, 99, 1, K_ABS) for i in range(4)]
    dop = [1, 0, 99, 0, 99, 99, 99, 60, 16, 0, 0, 0, 99, 99, 99, 0]
    dpg = [24, 0, 0, 0, 99, 99, 99, 99, 16, 0, 0, 0, 50, 50, 50, 50]
    return op + pg, dop + dpg


def alg_table():
    """56 x 16 B: n, carriers, feedback source, destination, the carriers' count, 3 spare, the mask (bit 8 d + s: s modulates d)"""
    out = bytearray()
    for i in range(V.NALG):
        a = V.alg_of(V.algs(), i)
        out += struct.pack("<5B3xQ", a["n"], a["car"], a["fs"], a["fd"], max(1, bin(a["car"]).count("1")), a["mask"])
    return bytes(out)


def alg_pad(page, pad):
    """the algorithm on pad 0..31 of the list's page (None: no algorithm there)"""
    if pad < 8:
        return None
    i = pad - 8
    if page == 0:
        return i if i < 16 else 48 + i - 16
    if page == 1:
        return 16 + i
    return 40 + i if i < 8 else None


ITAB, ITAB_END = 0x400, 0x2000                        # (OPT itab) the ITCM below dspz's window (0x2000-0x3FFF); 0x0-0x3FF left alone
IT_MAGIC = b"IT1\0"


def itab():
    """(RH86, OPT itab) the tables in the ITCM: packed in the flash (dspz's LZSS), unpacked at each core 0 upload (the boot's first DSP work,
    before any FM page or word): ~2.5 KB of flash"""
    import rhbuild
    return bool(rhbuild.OPT.get("itab"))


def itab_blob(data: bytes) -> bytes:
    """'IT1\0', the destination, the size, the LZSS stream (tests/rhemu.py unpacks it the same way when it maps the image)"""
    import dspz
    st = dspz._pack(data)
    assert dspz.unpack_stream(st, len(data)) == data
    return IT_MAGIC + struct.pack("<II", ITAB, len(data)) + st


def arm_code(base, L, prev):
    import rhbuild
    DEMOS = rhbuild.OPT.get("demos")                                      # (RH83: rpatch's demo patches)
    a = Asm(base)
    E = a.emit
    zc = [0]

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        if v >> 16:
            E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_f{zc[0]}"
        E(b_cond, n, GP.INV[cond])
        E(b, target)
        a.label(n)

    def udiv(rd, rn, rm): return h(0xFBB0 | rn) + h(0xF0F0 | rd << 8 | rm)
    def sdiv(rd, rn, rm): return h(0xFB90 | rn) + h(0xF0F0 | rd << 8 | rm)
    def rsbs(rd, rm): return h(0x4240 | rm << 3 | rd)

    # ---- the tables (OPT itab, RH86: packed here, unpacked into the ITCM at ITAB by c_itunp at each core 0 upload)
    ITB = itab()
    data = bytearray()
    T = {}

    def put(name, bs):
        while len(data) % 4:
            data.append(0)
        T[name] = (ITAB if ITB else base) + len(data)
        data.extend(bs)
    descs, defs = kd()
    put("slb", struct.pack("<128I", *V.SLB))
    put("alg", alg_table())
    put("t2", struct.pack("<49H", *V.T2))
    put("fxq", struct.pack("<100H", *V.FXQ))
    put("p10", struct.pack("<4H", *V.POW10))
    put("kd", bytes(b_ for d in descs for b_ in d))
    put("kdef", bytes(defs))
    put("opd", OP_DEF)
    put("inst", b"".join(I.compact(x) for x in I.INST))
    put("icol", bytes(b_ for x in I.INST for b_ in FP.ST_FAM[FAM[x["fam"]]]))
    put("acol", bytes(b_ for c in ALG_COL for b_ in c))
    put("zero", bytes((C.F_E, C.F_OFS, C.F_OUT, C.F_PH, C.F_R, C.F_AMP, C.F_AS, C.F_O2)))
    while len(data) % 4:
        data.append(0)
    import tabpack as TBP_
    if ITB and TBP_.v2():                                                 # (RH91, tabpack2) the tables in tabpack's stream, before the upload
        assert ITAB + len(data) <= ITAB_END
        TBP_.region("fm8page", [(bytes(data), 1)], at=ITAB, early=True)
    elif not ITB:
        E(raw, bytes(data))
    else:
        assert ITAB + len(data) <= ITAB_END
        blob = itab_blob(bytes(data))
        a.label("t_itab")
        E(raw, blob + bytes(-len(blob) % 4))

        # ---- c_itunp(): the tables into the ITCM (dspz's LZSS, the output its own window); clobbers r0-r3
        a.label("c_itunp")
        E(push_list, [4, 5, 6], lr=True)
        imm32(0, base + 12)                                               # the stream (the blob is the module's first bytes)
        imm32(1, ITAB)
        imm32(2, ITAB + len(data))
        E(movs_imm, 3, 1)
        a.label("iu_lp")
        E(cmp_reg, 1, 2)
        E(b_cond, "iu_x", "hs")
        E(cmp_imm, 3, 1)
        E(b_cond, "iu_f", "ne")
        E(ldrb_imm, 3, 0, 0)
        E(adds_imm8, 0, 1)
        E(movs_imm, 4, 1)
        E(lsls_imm, 4, 4, 8)
        E(orrs_reg, 3, 4)
        a.label("iu_f")
        E(lsrs_imm, 3, 3, 1)
        E(b_cond, "iu_m", "cc")
        E(ldrb_imm, 4, 0, 0)
        E(adds_imm8, 0, 1)
        E(strb_imm, 4, 1, 0)
        E(adds_imm8, 1, 1)
        E(b, "iu_lp")
        a.label("iu_m")                                                   # a match: (offset - 1) bits 0-12, length - 3 bits 13-15
        E(ldrb_imm, 4, 0, 0)
        E(ldrb_imm, 5, 0, 1)
        E(adds_imm8, 0, 2)
        E(lsls_imm, 5, 5, 8)
        E(orrs_reg, 4, 5)
        E(lsrs_imm, 5, 4, 13)
        E(lsls_imm, 4, 4, 19)
        E(lsrs_imm, 4, 4, 19)
        E(adds_imm8, 4, 1)
        E(cmp_imm, 5, 7)
        E(b_cond, "iu_n", "ne")
        E(ldrb_imm, 5, 0, 0)
        E(adds_imm8, 0, 1)
        E(adds_imm8, 5, 7)
        a.label("iu_n")
        E(adds_imm8, 5, 3)
        E(subs_reg, 4, 1, 4)
        a.label("iu_c")
        E(ldrb_imm, 6, 4, 0)
        E(adds_imm8, 4, 1)
        E(strb_imm, 6, 1, 0)
        E(adds_imm8, 1, 1)
        E(subs_imm8, 5, 1)
        E(b_cond, "iu_c", "ne")
        E(b, "iu_lp")
        a.label("iu_x")
        E(pop_list, [4, 5, 6], pc=True)

        # ---- c_f8up (the bl of core 0's upload, ahead of core0's c_d0up): the tables, then the upload as before
        a.label("c_f8up")
        E(push_list, [0, 1, 2], lr=True)
        E(bl, "c_itunp")
        E(ldr_sp, 0, 0)
        E(ldr_sp, 1, 4)
        E(bl, prev["d0up"])
        E(pop_list, [1, 2, 3], pc=True)
    ISZ = I.ISZ

    # ---- c_f8ram() -> r0 = our RAM (zeroed when its magic is missing); clobbers r1-r3
    a.label("c_f8ram")
    imm32(0, FMR)
    E(ldr_imm, 1, 0, 0)
    imm32(2, MAG)
    E(cmp_reg, 1, 2)
    E(b_cond, "rm_x", "eq")
    E(movs_imm, 1, 0)
    E(movs_imm, 3, RAM_LEN)
    a.label("rm_z")
    E(subs_imm8, 3, 4)
    E(raw, h(0x50C1))                                                     # str r1, [r0, r3]
    E(b_cond, "rm_z", "ne")
    E(raw, h(0x6002))                                                     # str r2, [r0]
    a.label("rm_x")
    E(raw, h(0x4770))

    # ---- c_f8rd(r0 = slot, r1 = i) -> r0 = its parameter byte; clobbers r1-r3
    a.label("c_f8rd")
    if pclr():                                                            # (RH90) a preset's copy instead (rpatch's, while it asks)
        imm32(2, 0x33f0)
        E(ldr_imm, 2, 2, 0)
        E(cmp_imm, 2, 0)
        E(b_cond, "rd_n", "eq")
        E(ldrb_reg, 0, 2, 1)
        E(raw, h(0x4770))
        a.label("rd_n")
    E(push_list, [4], lr=True)
    E(lsls_imm, 0, 0, 8)
    E(adds_reg, 1, 1, 0)
    E(movw, 0, PB)
    E(adds_reg, 1, 1, 0)
    E(movs_imm, 0, 0)
    E(bl, L["c_d16r"])
    E(lsrs_imm, 0, 0, 8)
    E(movs_imm, 1, 0xFF)
    E(ands_reg, 0, 1)
    E(pop_list, [4], pc=True)

    # ---- c_f8wr(r0 = slot, r1 = i, r2 = value): the parameter byte; c_f8ww(r0 = slot, r1 = offset, r2 = word): a word of its block;
    #      clobber r0-r3
    a.label("c_f8wr")
    E(push_list, [4], lr=True)
    E(lsls_imm, 0, 0, 8)
    E(adds_reg, 3, 1, 0)
    E(movw, 0, PB)
    E(b, "wr_w")
    a.label("c_f8ww")
    E(push_list, [4], lr=True)
    E(lsls_imm, 0, 0, 9)
    E(adds_reg, 3, 1, 0)
    E(movw, 0, C.FB0)
    a.label("wr_w")
    E(adds_reg, 3, 3, 0)
    E(lsls_imm, 1, 2, 8)
    E(mov_reg, 2, 3)
    E(movs_imm, 0, 0)
    E(bl, TH.WR16)
    E(pop_list, [4], pc=True)

    # ---- c_f8wk(r1 = field, r2 = word; r4 = the slot, r7 = the operator, 8 = the pitch envelope): its block's field; clobbers r0-r3
    a.label("c_f8wk")
    E(push_list, [4], lr=True)
    E(lsls_imm, 0, 7, 5)
    E(adds_reg, 1, 1, 0)
    E(adds_imm8, 1, C.OP0)
    E(mov_reg, 0, 4)
    E(bl, "c_f8ww")
    E(pop_list, [4], pc=True)

    # ---- c_f8src(r0 = slot) -> r0 = the slot whose parameters it plays (a borrowed poly slot: its track's first); clobbers r1-r3
    a.label("c_f8src")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, L["c_fmram"])
    E(cmp_imm, 0, 0)
    E(b_cond, "sr_s", "eq")
    E(ldrb_w, 0, 0, FP.R_BORR)
    E(lsrs_reg, 0, 4)
    E(lsls_imm, 0, 0, 31)
    E(b_cond, "sr_s", "eq")
    imm32(1, (S.Y0 + S.C_TRK) | 0x8000)
    E(lsls_imm, 0, 4, 6)                                                  # SN = $40
    E(adds_reg, 1, 1, 0)
    E(movs_imm, 0, 0)
    E(bl, L["c_d16r"])
    E(lsrs_imm, 0, 0, 8)
    E(subs_imm8, 0, 1)
    E(cmp_imm, 0, 7)
    E(b_cond, "sr_s", "hi")
    E(bl, L["c_syslot"])
    E(cmp_imm, 0, NSL)
    E(b_cond, "sr_x", "lo")
    a.label("sr_s")
    E(mov_reg, 0, 4)
    a.label("sr_x")
    E(pop_list, [4], pc=True)

    # ---- c_f8dirty(r0 = slot, r1 = items): to make, the borrowed slots that play its parameters too; clobbers r0-r3
    a.label("c_f8dirty")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(bl, "c_f8ram")
    E(mov_reg, 6, 0)
    E(movs_imm, 7, 0)
    a.label("dy_l")
    E(cmp_reg, 7, 4)
    E(b_cond, "dy_m", "eq")
    E(mov_reg, 0, 7)
    E(bl, "c_f8src")
    E(cmp_reg, 0, 4)
    E(b_cond, "dy_n", "ne")
    a.label("dy_m")
    E(lsls_imm, 0, 7, 1)
    E(adds_reg, 0, 0, 6)
    E(ldrh_imm, 1, 0, O_DIRTY)
    E(orrs_reg, 1, 5)
    E(strh_imm, 1, 0, O_DIRTY)
    a.label("dy_n")
    E(adds_imm8, 7, 1)
    E(cmp_imm, 7, NSL)
    E(b_cond, "dy_l", "lo")
    E(pop_list, [4, 5, 6, 7], pc=True)

    # ---- c_f8load(r0 = slot, r1 = instrument 0-23): its 216 parameters (fm8inst.inst_full byte for byte); clobbers r0-r3
    # (rpatch demos: c_f8load(r0 = an address, r1 = the instrument) = its 216 parameter bytes into that buffer; clobbers r0-r3)
    a.label("c_f8load")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(mov_reg, 4, 0)
    E(movs_imm, 0, ISZ)
    E(muls, 0, 1)
    E(adds_imm8, 1, 1)
    E(push_list, [1])                                                     # [sp] = the instrument + 1
    imm32(5, T["inst"])
    E(adds_reg, 5, 5, 0)                                                  # r5 = its compact record
    E(movs_imm, 6, 0)                                                     # r6 = the parameter
    a.label("ld_l")
    E(movs_imm, 2, 0)
    E(cmp_imm, 6, 192)
    E(b_cond, "ld_g", "hs")
    E(movs_imm, 0, V.OPB)
    E(mov_reg, 1, 6)
    E(raw, udiv(3, 1, 0))                                                 # r3 = the operator
    E(muls, 0, 3)
    E(subs_reg, 7, 6, 0)                                                  # r7 = its field
    E(movs_imm, 0, I.OPB_C)
    E(muls, 0, 3)
    E(adds_reg, 0, 0, 5)                                                  # r0 = its compact bytes
    E(cmp_imm, 7, 8)
    E(b_cond, "ld_o1", "hs")
    E(ldrb_reg, 2, 0, 7)                                                  # R1-R4, L1-L4
    E(b, "ld_w")
    a.label("ld_o1")
    for fld, src, sh, mask in ((V.O_BP, None, 0, 39), (V.O_RD, 13, 0, 0xFF), (V.O_RS, 12, 3, 7), (V.O_KVS, 12, 0, 7), (V.O_OL, 8, 0, 0xFF),
                               (V.O_MODE, 12, 6, 3), (V.O_CRS, 9, 0, 0xFF), (V.O_FINE, 10, 0, 0xFF), (V.O_DET, 11, 0, 0xFF)):
        E(cmp_imm, 7, fld)
        E(b_cond, f"ld_n{fld}", "ne")
        if src is None:
            E(movs_imm, 2, mask)
        else:
            E(ldrb_imm, 2, 0, src)
            if sh:
                E(lsrs_imm, 2, 2, sh)
            if mask != 0xFF:
                E(movs_imm, 1, mask)
                E(ands_reg, 2, 1)
        E(b, "ld_w")
        a.label(f"ld_n{fld}")
    E(b, "ld_w")
    a.label("ld_g")
    E(cmp_imm, 6, 200)
    E(b_cond, "ld_gl", "hs")
    E(subs_imm8, 6, 192)                                                  # the pitch envelope
    E(adds_reg, 0, 5, 6)
    E(adds_imm8, 0, 8 * I.OPB_C)
    E(ldrb_imm, 2, 0, 0)
    E(adds_imm8, 6, 192)
