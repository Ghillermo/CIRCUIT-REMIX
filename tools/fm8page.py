def install(img, report, base_addr):
    """The heads of the pad press / release (ahead of fmpage's), the knob slot (ahead of synthpage's), the button chain and the LED calls.
    Needs fmpage (OPT fm8page), synthpage, smodes, stockplus, kbright, cthresh, latch (its RAM's end), fm8c0 on core 0 (OPT fm8) and c_d16r."""
    import rhbuild
    BASE = rhbuild.BASE
    u = lambda a_: struct.unpack_from("<I", img, a_ - BASE)[0]                 # noqa: E731
    lab = lambda m, k: int(report[m]["labels"][k], 16)                         # noqa: E731
    assert rhbuild.OPT.get("fm8") and rhbuild.OPT.get("fm8page") and "latch" in report
    d16 = report.get("rdiag", {}).get("labels", {}).get("c_d16r") or report["dsprd"]["labels"]["c_d16r"]
    L = dict(c_rst=lab("rhstate", "c_rst"), c_ciok=lab("countin", "c_ciok"), c_spshift=lab("stockplus", "c_spshift"),
             c_spheld=lab("stockplus", "c_spheld"), c_spview=lab("stockplus", "c_spview"), c_sypage=lab("synthpage", "c_sypage"),
             c_syslot=lab("synthpage", "c_syslot"), c_smview=lab("smodes", "c_smview"), c_fmram=lab("fmpage", "c_fmram"),
             c_fmon=lab("fmpage", "c_fmon"), c_d16r=int(d16, 16))
    prev = dict(pad=rhbuild.bw_target(img, GP.PP_ENTRY), rel=rhbuild.bw_target(img, GP.PR_ENTRY), knob=u(SY.SLOT_KNOB) & ~1,
                btn=rhbuild.bw_target(img, CI.BTN_ENTRY), ledtask=rhbuild.bl_target(img, CI.LED_CALLS[0]))
    assert all(rhbuild.bl_target(img, c) == prev["ledtask"] for c in CI.LED_CALLS)
    if itab():
        import core0
        prev["d0up"] = rhbuild.bl_target(img, core0.UPLOAD_BL0)
        assert prev["d0up"] == int(report["core0"]["labels"]["c_d0up"], 16)
    code_, labels = arm_code(base_addr, L, prev)
    img += bytes([0xFF]) * (base_addr - BASE - len(img)) + code_
    while len(img) % 4:
        img += bytes([0xFF])
    rhbuild.patch(img, GP.PP_ENTRY, f"b.w #{prev['pad']:#x}", b_w(GP.PP_ENTRY, labels["c_f8pad"]))
    rhbuild.patch(img, GP.PR_ENTRY, f"b.w #{prev['rel']:#x}", b_w(GP.PR_ENTRY, labels["c_f8rel"]))
    rhbuild.patch_word(img, SY.SLOT_KNOB, prev["knob"] | 1, labels["c_f8knob"] | 1)
    rhbuild.patch(img, CI.BTN_ENTRY, f"b.w #{prev['btn']:#x}", b_w(CI.BTN_ENTRY, labels["c_f8btn"]))
    for c in CI.LED_CALLS:
        rhbuild.patch(img, c, f"bl #{prev['ledtask']:#x}", bl(c, labels["c_f8led"]))
    import tabpack as TBP_
    if itab() and not TBP_.v2():
        import core0
        rhbuild.patch(img, core0.UPLOAD_BL0, f"bl #{prev['d0up']:#x}", bl(core0.UPLOAD_BL0, labels["c_f8up"]))
    report["fm8page"] = dict(prev={k: hex(v) for k, v in prev.items()}, labels={k: hex(v) for k, v in labels.items() if k.startswith("c_")},
                             tables={k: hex(v) for k, v in labels.items() if k.startswith("t_")})
    return labels, code_
