def install(img, report, base_addr):
    """The container's knob slot, the pad press and release, the LED calls, the note entry, the players' slot 4, the parameter dump, the inner
    function's and the gate's vtable words; the reads and the automation sites at their labels (mxsink / mxlane).  Needs what the docstring lists."""
    import rhbuild
    BASE = rhbuild.BASE
    lab = lambda m, k: int(report[m]["labels"][k], 16)                         # noqa: E731
    u = lambda a_: struct.unpack_from("<I", img, a_ - BASE)[0]                 # noqa: E731
    L = dict(c_rram=lab("rhstate", "c_rram"), c_rst=lab("rhstate", "c_rst"), c_rrt=lab("rhrec", "c_rrt"), c_ciok=lab("countin", "c_ciok"),
             c_arpat=lab("autorel", "c_arpat"), c_tcget=lab("trkcopy", "c_tcget"), c_aiknob=lab("autoinit", "c_aiknob"),
             **{k: lab("synthpage", k) for k in ("c_syslot", "c_syv", "c_syp", "c_syb", "c_sypage", "c_sypend", "c_sysnd")},
             **{k: lab("spall", k) for k in ("c_wsget", "c_wsset", "c_s0snd")},
             c_ckrec=lab("clkci", "c_ckrec"), c_aiinit=lab("autoinit", "c_aiinit"),
             **{k: lab("granpage", k) for k in ("c_gnslot", "c_gnv", "c_gnp", "c_gnb", "c_gnpend", "c_gpmst", "c_gpmopen", "c_gpb", "c_gpinit", "c_gpfix")},
             **{k: lab("stockplus", k) for k in ("c_spview", "c_spheld", "c_spshift", "c_spval", "c_spput", "c_spdirty", "c_spst")})
    XL = rhbuild.OPT.get("mxx", False)
    if XL:
        L.update(c_aiprev=lab("autoinit", "c_aiprev"), c_airam=lab("autoinit", "c_airam"), c_aiclr=lab("autoinit", "c_aiclr"),
                 c_cinew=lab("countin", "c_cinew"))
    prev = dict(knob=u(SK.SLOT_KNOB) & ~1, ledtask=rhbuild.bl_target(img, CI.LED_CALLS[0]), pad=rhbuild.bw_target(img, GP.PP_ENTRY),
                rel=rhbuild.bw_target(img, GP.PR_ENTRY), note=rhbuild.bw_target(img, TF.NOTE_DSP), s4=u(SLOT4) & ~1,
                dump=rhbuild.bl_target(img, DUMP_CALL), srel=u(AR.SV_VT + 4) & ~1)
    assert all(rhbuild.bl_target(img, c) == prev["ledtask"] for c in CI.LED_CALLS)
    assert u(INNER_VT) == INNER_FN | 1 and u(GATE_SLOT) == GATE_THUNK
    code_, labels = arm_code(base_addr, L, prev)
    img += bytes([0xFF]) * (base_addr - BASE - len(img)) + code_
    while len(img) % 4:
        img += bytes([0xFF])
    rhbuild.patch_word(img, SK.SLOT_KNOB, prev["knob"] | 1, labels["c_mxknob"] | 1)
    for c in CI.LED_CALLS:
        rhbuild.patch(img, c, f"bl #{prev['ledtask']:#x}", bl(c, labels["c_mxled"]))
    for site, key, lb in ((GP.PP_ENTRY, "pad", "c_mxpad"), (GP.PR_ENTRY, "rel", "c_mxrel"), (TF.NOTE_DSP, "note", "c_mxnote")):
        rhbuild.patch(img, site, f"b.w #{prev[key]:#x}", b_w(site, labels[lb]))
    rhbuild.patch_word(img, SLOT4, prev["s4"] | 1, labels["c_mxstep"] | 1)
    rhbuild.patch(img, DUMP_CALL, f"bl #{prev['dump']:#x}", bl(DUMP_CALL, labels["c_mxdump"]))
    rhbuild.patch_word(img, INNER_VT, INNER_FN | 1, labels["c_mxinner"] | 1)
    rhbuild.patch_word(img, GATE_SLOT, GATE_THUNK, labels["c_mxgatet"] | 1)
    for m, k, tgt, lb in (("stockplus", "c_spvd", L["c_spval"], "c_mxspv"), ("synthpage", "c_sywv", L["c_syv"], "c_mxsyv"), ("spall", "c_wsvd", L["c_wsget"], "c_mxwsv")):
        rhbuild.patch(img, lab(m, k), f"b.w #{tgt:#x}", b_w(lab(m, k), labels[lb]))
    for k in ("c_evk2",) if report["synthpage"].get("va") else ("c_evk1", "c_evk2"):   # (RH77, va: the start reads its raw value)
        site = lab("envpage", k)
        rhbuild.patch(img, site, f"bl #{L['c_syv']:#x}", bl(site, labels["c_mxsyv"]))
    site = lab("autoinit", "c_aisk")
    rhbuild.patch(img, site, f"bl #{L['c_tcget']:#x}", bl(site, labels["c_mxkg"]))
    site = lab("autoinit", "c_aiin1")
    rhbuild.patch(img, site, f"bl #{L['c_aiinit']:#x}", bl(site, labels["c_mxinit"]))
    site = lab("granpage", "c_gnwv")
    rhbuild.patch(img, site, f"bl #{L['c_gnv']:#x}", bl(site, labels["c_mxgnv"]))
    site = lab("autorel", "c_arbg")
    rhbuild.patch(img, site, f"bl #{AR.GROUP_GET:#x}", bl(site, labels["c_mxbase"]))
    site = lab("autorel", "c_arrem")
    rhbuild.patch(img, site, "movs r0, #0|bx lr", b_w(site, labels["c_mxrem"]))
    site = lab("autoinit", "c_aikg")
    rhbuild.patch(img, site, f"bl #{L['c_tcget']:#x}", bl(site, labels["c_mxkg"]))
    for k in ("c_aiks1", "c_aiks2"):
        site = lab("autoinit", k)
        rhbuild.patch(img, site, f"bl #{L['c_aiknob']:#x}", bl(site, labels["c_mxks"]))
    if XL:
        rhbuild.patch_word(img, AR.SV_VT + 4, prev["srel"] | 1, labels["c_mxsvr"] | 1)
        site = lab("autoinit", "c_aipv")
        rhbuild.patch(img, site, f"bl #{L['c_aiprev']:#x}", bl(site, labels["c_mxprev"]))
        site = lab("autoinit", "c_airamp")
        rhbuild.bl_target(img, site)
        rhbuild.patch(img, site, f"bl #{rhbuild.bl_target(img, site):#x}", bl(site, labels["c_mxramp"]))
        site = lab("autoinit", "c_aicl1")
        rhbuild.patch(img, site, f"bl #{L['c_aiclr']:#x}", bl(site, labels["c_mxaic"]))
        for site, tgt, lb in ((PCLR_CALL, PCLR, "c_mxpclr"), (SCLR_CALL, SCLR, "c_mxsclr"), (DUP_CALL, DUP, "c_mxdup")):
            rhbuild.patch(img, site, f"bl #{tgt:#x}", bl(site, labels[lb]))
    report["modmx"] = dict(prev={k: hex(v) for k, v in prev.items()}, block=hex(BLK), labels={k: hex(v) for k, v in labels.items() if k.startswith("c_")})
    return labels, code_
