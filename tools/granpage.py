        E(cmp_imm, 0, 127)
        E(b_cond, f"lw_{k}", "le")
        E(movs_imm, 0, 127)
        E(b, f"lw_{k}")
        a.label(f"lu_{k}")
        E(lsrs_imm, 0, 0, 7)
