    E(ldrb_imm, 1, 7, O_DUPA)
    E(cmp_reg, 0, 1)
    E(b_cond, "ld_a", "ne")
    E(movs_imm, 3, 0)
    E(cmp_imm, 2, 0)
    E(b_cond, "ld_a", "eq")
    E(movs_imm, 3, COL_A)
    a.label("ld_a")
    E(ldrb_imm, 1, 7, O_CLR)
    E(cmp_reg, 0, 1)
    E(b_cond, "ld_c", "ne")
    E(ldr_sp, 1, 4)
    E(push_list, [0])
    E(ldr_imm, 0, 7, O_TCLR)
    E(subs_reg, 1, 1, 0)
    E(pop_list, [0])
    E(movw, 2, HOLD_CLR)
    E(cmp_reg, 1, 2)
