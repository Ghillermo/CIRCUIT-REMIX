    E(b_cond, "bw_x", "eq")
    E(movs_imm, 1, TB)
    E(muls, 1, 4)
    E(adds_reg, 0, 0, 1)
    E(lsrs_imm, 1, 5, 3)
    E(adds_reg, 4, 0, 1)                                                  # r4 = the bytes
    E(movs_imm, 2, 7)
    E(ands_reg, 2, 5)                                                     # r2 = the shift
    E(movs_imm, 1, 1)
    E(lsls_reg, 1, 6)
    E(subs_imm8, 1, 1)
    E(lsls_reg, 1, 2)                                                     # r1 = the mask
    E(ldrb_imm, 3, 4, 1)
    E(lsls_imm, 3, 3, 8)
    E(ldrb_imm, 0, 4, 0)
    E(orrs_reg, 0, 3)
    E(bics_reg, 0, 1)
    E(lsls_reg, 7, 2)
    E(ands_reg, 7, 1)
    E(orrs_reg, 0, 7)
    E(strb_imm, 0, 4, 0)
    E(lsrs_imm, 0, 0, 8)
    E(strb_imm, 0, 4, 1)
    a.label("bw_x")
    E(pop_list, [4, 5, 6, 7], pc=True)

