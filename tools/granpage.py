def model_engine(v, k):
    """the engine's value of knob k at the 14-bit value v (as the ARM computes it)"""
    return (((v >> 7) * MUL[k]) >> 7) - OFFS[k]


def popw(regs, lr=False): return h(0xE8BD) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0))


def model_gn(slots):
    """(multi) the project's block for [(track + 1, [13 values >> 7])] (the tests')"""
    b = bytearray(GN_LEN)
    b[0] = GN_MARK
    for k, (t1, vals) in enumerate(slots):
        b[2 + GN_SLOT * k] = t1
        b[3 + GN_SLOT * k:3 + GN_SLOT * k + len(vals)] = bytes(vals)
    c = GN_CHECK
    for x in b[2:]:
        c ^= x
    b[1] = c
    return bytes(b)


