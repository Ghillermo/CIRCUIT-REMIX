"""The sample arpeggiator (MIT; CIRCUIT-HACKS' drumarp of SC42.8 / SC43.7 (rate order) for the Circuit Rhythm 5706).  The user (2026-10-19):
«9: shift+25, como en Tracks».  Several sample pads held in a track's view = an arpeggio of those samples on the track.

The stock of the Rhythm (read in the firmware and on the RAM dump, emulated):
  * a track's view: its sample pads (17-32) reach slot 0 of that track's sample view (0x200490A4 + 0xE4 t, vtable 0x08068294; 0x0805C1AC(view,
    pad 0..15, velocity)), release slot 1 (0x0805C2BE); a press plays the sample page x 16 + pad and holds it in p0 of the store [view + 0x3C]
    (0xFF none), the release selects it (the player's selection, p0 of [player + 0x60]); with a step held (p1 of [view + 0x3C] = the step,
    else 0xFF) it is the step's sample flip;
  * the players 0x200470D4 + 0x190 t (drumpat.py): [+ 0x58] slot 0 sets the sample, the note-on 0x0804B0D4, the voice release 0x0804B19E,
    slot 2 = every micro step (player, pattern, step, micro step); the rate = p1 of [player + 0x10], its ticks a step = [0x08068D9C + 4 rate]
    (2, 3, 4, 6, 8, 12, 16, 24: 1/32T .. 1/4); the pattern a track plays = p0 of [0x2003C380 + 0x30 + 4 t];
  * Pattern Settings (0x2004C4B8 + 0x60 t, vtable 0x08067EA4): Shift + pads 17-24 / 29-32 = the plain pads (sync rate / direction), Shift +
    25-28 = nothing / ours without Shift (checked in tests/emu_stock.py).

Ours (as CIRCUIT-HACKS'):
  * the setting: a byte per track and pattern (bit 7 on, bits 0-2 the order, bits 3-6 the resolution: 0 the track's sync rate, 1..8 = 1/32T ..
    1/4) in the record's tail (rhrec "drumarp": "AD", a sum, 64 bytes; saved with the project); Pattern Settings, Shift held: pad 25 on / off,
    pads 27-32 the order (fractal, deconstructed, up, down, ping-pong, random), pads 17-24 the resolution (pad 17 = 1/4 .. pad 24 = 1/32T, the
    stock's sync rate order; the same again = the track's own); with Shift their LEDs: pad 25 green while on (dim off), the chosen ones green;
  * the input: in the view of a track whose playing pattern has it on (no Shift / Clear / Duplicate, no step held), the first sample pad held
    is the stock's; a second one held with it is not the stock's (no selection, no sound) and starts the arpeggio of the samples held (6 at
    most, sorted), in the chosen order: each hit sets the track's sample through the player (as a sample flip) and plays it with its pad's
    velocity; while playing on the track's grid of micro steps (the players' slot 2), stopped from the LED task at the project's tempo; it goes
    on while any sample is held; at the end the track's selected sample again; not recorded;
  * the running state in our RAM (rhstate "drumarp"); the sample view's LEDs stamp it: no view for 200 ms = stopped.
"""
