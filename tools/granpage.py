    E(adds_imm8, 1, 1)
    E(movs_imm, 0, 3)
    E(bl, "c_gpsetb")
    a.label("bn_d")
    E(movs_imm, 0, 1)
    E(bl, "c_gpdirty")
    E(raw, popw([0, 1, 2, 4, 5, 6, 7], lr=True))
    E(b_w, prev["stock_btn"])                                             # the stock's press, past stockplus's flip
    a.label("bn_p")
