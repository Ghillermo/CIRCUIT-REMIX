def install(img, report, base_addr):
    """Append the code; in front: the pad press / release chains, the Mixer's knob slot, the players' slot 4, the LED calls.  Needs
    fxseq (its RAM room, c_fxmix), drybus with OPT looper on core 0 (looper0's body)."""
    import rhbuild
    import rhstate
    import cthresh as TH
    BASE = rhbuild.BASE
    u = lambda a_: struct.unpack_from("<I", img, a_ - BASE)[0]          # noqa: E731
    lab = lambda sec, n: int(report[sec]["labels"][n], 16)              # noqa: E731
    assert "fxseq" in report and rhbuild.OPT.get("looper")
    assert FX.RAM_LEN_S <= 96 and 296 + 96 + LP_LEN <= rhstate.OFF2["modmx"][1]
    L = dict(c_ciok=lab("countin", "c_ciok"), c_cishift=lab("countin", "c_cishift"), c_cinew=lab("countin", "c_cinew"),
             c_rst=lab("rhstate", "c_rst"), c_fxmix=lab("fxseq", "c_fxmix"),
             c_d16r=lab("rdiag" if "rdiag" in report else "dsprd", "c_d16r"),
             O_TH=rhstate.OFF["cthresh"][0] + 1, READY=TH.READY, WR16=TH.WR16, O_KB=rhstate.OFF["kbright"][0])
    prev = dict(pad=rhbuild.bw_target(img, GP.PP_ENTRY), rel=rhbuild.bw_target(img, GP.PR_ENTRY), knob=u(FX.MIX_SLOT_KNOB) & ~1,
                s4=u(FX.SLOT4) & ~1, ledtask=rhbuild.bl_target(img, CI.LED_CALLS[0]))
    assert all(rhbuild.bl_target(img, c) == prev["ledtask"] for c in CI.LED_CALLS)
    code_, labels = arm_code(base_addr, L, prev)
    img += bytes([0xFF]) * (base_addr - BASE - len(img)) + code_
    while len(img) % 4:
        img += bytes([0xFF])
    rhbuild.patch(img, GP.PP_ENTRY, f"b.w #{prev['pad']:#x}", b_w(GP.PP_ENTRY, labels["c_lppad"]))
    rhbuild.patch(img, GP.PR_ENTRY, f"b.w #{prev['rel']:#x}", b_w(GP.PR_ENTRY, labels["c_lprel"]))
    rhbuild.patch_word(img, FX.MIX_SLOT_KNOB, prev["knob"] | 1, labels["c_lpknob"] | 1)
    rhbuild.patch_word(img, FX.SLOT4, prev["s4"] | 1, labels["c_lps4"] | 1)
    for c in CI.LED_CALLS:
        rhbuild.patch(img, c, f"bl #{prev['ledtask']:#x}", bl(c, labels["c_lpled"]))
    report["looper"] = dict(prev={k: hex(v) for k, v in prev.items()}, ram=hex(LPR),
                            labels={k: hex(v) for k, v in labels.items() if k.startswith("c_")})
    return labels, code_
