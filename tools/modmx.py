"""The modulation matrix and the two views of controls (MIT; RH64; the user, 2026-11-01: «matriz de modulación, vista de controles secuenciables
y vista de controles no secuenciables»; every track, three pads of their own: pad 6, pad 7, pad 16; «automatizaciones adicionales (se iría
rellenando automáticamente según se graben)»).  CIRCUIT-HACKS' modmx (SC44.2) for the Rhythm's tracks, with the destinations of every page.

The destinations, 32 by track, one pad each while a destination is chosen (pads 1-32):
  * 0-7  the stock's K1-K8; 8-15 Stock+'s K1-K8 (K7 = stretch on a sample track, the waveshaper's amount on a granular or synth one);
  * 16-31 the sound's page: a synth slot's 16 values, a granular slot's 13, a sample track's Stock+ Shift + K5-K8 (16-19, the rest none); on a line
    track only the stock's K (it has no Stock+).  The last destination has 15 amounts: 9 bits hold 0..511.
The pages (RAM, a track's): the track menu's pad 6 = the matrix (0x62 / 0x63), pad 7 = sequenceable (0x35 / 0x36), pad 16 = non-sequenceable
(0x3F / 0x40); a tap keeps the page, held it lasts until let go; another page pad takes ours off.  They go over the others' pages.
  * Matrix: K1-K8 = the sources: velocity, note, random (each note), LFO 2, envelope 2, hit of a chosen track, the pattern's position, step random.
    A knob's position = destination + amount: 0 off, then 16 clicks a destination; LED = the destination page's colour, its brightness the
    amount; pads 1-32 show where it goes for 1.5 s.  Shift + K4 LFO 2: 4 zones (triangle, saw, square, sample & hold: the shape's colour) of 32
    rates, each zone bipolar as CIRCUIT-HACKS' (the first half to the tempo, the fastest at the zone's start; the second free, faster upwards; dark
    at the zone's centre); + K5 envelope 2 (4 attacks, a colour each, x 32 decays), + K6 the track (its colour) and its decay, + K8 steps a new
    value (1, 2, 4, 8).  Clear + knob = off; Clear + Shift + knob = its parameter's default.  On our pages a bipolar destination's LED is dark at
    its centre; the filter type and the waves show their own colour.
  * Sequenceable: K1-K8 = the 8 automation lanes; each knob moves its lane's destination and records into the lane.  Shift + knob = the lane's
    destination (4 clicks each); Clear + knob = the lane erased in the 8 patterns, its destination back to stock K(k).
  * Non-sequenceable: K1-K8 move their destination (by default Stock+'s K1-K8) and nothing records them, not even with Record on.  Shift + knob
    = the destination; Clear + knob = its default.
The automatic lanes: a track has 8 knob lanes, each lane's destination is ours (default the stock's K(k)).  A knob turned with Record on on the
Stock+, Granular or Synth pages (without Shift) records too: into the lane of its destination, or the highest free lane (its default destination,
no data in the track's 8 patterns), which takes that destination, so the Sequenceable page fills itself; none free = not recorded.  The stock's own
knobs the same.  A lane given another destination stays so until Clear + its knob on the Sequenceable page.
  * playback and writes: every parameter write ends in the router's inner function 0x08049B28(inner, id, value, flag) (vtable 0x080696AC; the
    router 0x20043740 = flag 1, its twin 0x20043758, the players' [+ 0x2C], = flag 3); ours, at the vtable, takes flag 3 for ids 0x10 t + 0..7
    (and + 14, + 15, the low bits of K2 / K3): lane -> destination.  Ours write with flag 3, which never records;
  * recording: the gate 0x08036B06(0x20040D88, id, value), reached by its second vtable 0x08068CF8's slot 0 (a thunk, subs r0, #4), with the object
    0x20040D8C = [0x20043700 + 0x10]: id = 0x10 t + a knob, recording -> its lane;
  * autorel's bases and Project init, autoinit's preview and snapshot go through the mapping (patched `bl`s at their labels).
The sinks of the offsets (RAM off[t][d], 14 bits, each frame): the stock's K through the parameter dump (bl 0x0803085E, ahead of slink; their
dirty bits set when an offset moves); Stock+ through c_spdsp / c_s0dsp's reads (c_spvd), a slot's words through c_gnw's and c_syword's reads
(their labels); one track's engine words a frame; the track's byte 0x20006B50 goes with the dirty bits, so the periodic flush sends them between
notes (a note's own sources reach the stock's K one LED frame after it).  The page's knobs and the project keep the base values.
RH65 (mxx; CIRCUIT-HACKS' lanex and slock's ramps, for the Rhythm):
  * the extra lane: a ninth lane a track, one value 0..126 a step, in bits 1-7 of the step's byte 7 (autorel's mark is bit 0; 0 = nothing, else the
    value + 1; byte 7 goes with the step in Nudge, paste, Mutate, the quantize and Duplicate of a pattern): it takes the first destination (all but
    the last) that finds no lane while recording; its destination + 1 is the track's: 5 bits, the low 4 in the tail (rhrec "xlane"), bit 4 in the
    block "MX"'s byte 3, as no pattern operation reaches them.  It plays at each step's start (the slot 4 head).  Clear + a pattern or + a step
    erases its values there, Clear + Shift + a knob of the Sequenceable page in the 8 patterns.  State locks are not needed here: the Rhythm has
    8 lanes with 6 micro steps, the snapshot (Record + step) already keeps all 8 lanes of a step at full resolution;
  * ramps: the automation view, a yellow step held + another step pressed: each knob lane with a value at either end gets the straight line
    between them, micro step by micro step (the value now where an end has none).
Saved: the tail block "MX" (rhrec.OFF54): "M", "X", a version, the extra lanes' bit 4, then 19 B a track: 8 x 9 bits the position, 8 x 5 bits the lanes, 8 x 5 bits the
non-sequenceable (destinations XOR their default index): no marker = all default, made at the first write; 3 B a track of parameters in the
legacy bytes of the block «GP» (+ 6; XOR PAR_DEF: LFO 2 | steps bit 0 << 7, envelope 2 | steps bit 1 << 7, track << 5 | decay), c_gpfix after.
"""
