CONT, SUBVIEW = SP.CONT, SP.SUBVIEW
ONE = F.ONE


def alg_bytes(a, i):
    car = sum(1 << (c - 1) for c in a["car"])
    sus = sum(1 << k for k in range(4) if a["sus"][k])
    flags = (1 if a["pitch"] else 0) | (a["noise"] - 1) << 4
    fb = (a["fb"] - 1) if a["fb"] else 0xFF
    kw = 0x3FFFFF // len(a["car"])
    det = [round(4096 * x) for x in a["det"]]
    rof = [x & 0xFF for x in a["relofs"]]
    import struct
    return struct.pack("<HBBBBBBI4H4B", a["mask"], car, sus, flags, fb, a["fam"], V.VS[i], kw, *det, *rof)


A_MASK, A_CAR, A_SUS, A_FLG, A_FB, A_FAM, A_VS, A_KW, A_DET, A_ROF, ALEN = 0, 2, 3, 4, 5, 6, 7, 8, 12, 20, 24


def model_word(vals, slot_on, i):
    """(the tests') word i of a slot: (X address offset in the block, value)"""
    w = V.words(vals, VEL, NOTE)
    if i < 4 * len(V.PARAMS):
        o = (i // len(V.PARAMS)) * F.FMS + V.PARAMS[i % len(V.PARAMS)]
    elif i < 4 * len(V.PARAMS) + len(V.GLOBALS):
        o = V.GLOBALS[i - 4 * len(V.PARAMS)]
    else:
        return F.G_KEY, F.FMKEY if slot_on else 0
    return o, w[o] & 0xFFFFFF


def arm_code(base, L, prev, poly=False):
    import rhbuild
    FM8 = bool(rhbuild.OPT.get("fm8page"))                                # (RH76) the 8-operator FM: tools/fm8page.py has the words and knobs
    a = Asm(base)
    E = a.emit
    zc = [0]

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_m{zc[0]}"
        E(b_cond, n, GP.INV[cond])
        E(b, target)
        a.label(n)

    def umull(lo, hi, rn, rm):
        return h(0xFBA0 | rn) + h(lo << 12 | hi << 8 | rm)

    import struct
    # ---- the tables
    data = bytearray()
    T = {}

    def put(name, bs):
        while len(data) % 4:
            data.append(0)
        T[name] = base + len(data)
        data.extend(bs)
    if FM8:
        put("def", bytes(V.DEFAULTS2))
    else:
        put("rat", struct.pack("<24I", *V.T_RAT))
        put("atk", struct.pack("<32I", *V.T_ATK))
        put("coef", struct.pack("<64I", *V.T_COEF))
        put("alg", b"".join(alg_bytes(x, i) for i, x in enumerate(V.ALGS)))
        put("def", bytes(V.DEFAULTS2))
        put("st", b"".join(bytes(v) for _, v in V.starters()))              # (RH71, OPT fmst2: the retuned set)
        put("stc", b"".join(bytes(ST_FAM[f]) for f in ST_OF))
        put("fam", bytes(FAM_COL))
        put("par", bytes(V.PARAMS))
        put("glb", bytes(V.GLOBALS))
        put("clr", bytes([o for o in range(4 * F.FMS) if o % F.FMS in (F.F_OUT, F.F_PH, F.F_R, F.F_AMP, F.F_AS, F.F_O2, F.F_E, F.F_ST)]
                         + [F.G_NA, F.G_NS]))
    while len(data) % 4:
        data.append(0)
    E(raw, bytes(data))
    n_clr = 4 * 8 + 2

    # ---- c_fmram() -> r0 = our RAM (made anew when its signature is missing), 0 without; clobbers r1-r3
    a.label("c_fmram")
    E(push_list, [4], lr=True)
    E(bl, L["c_rram"])
    E(cmp_imm, 0, 0)
    E(b_cond, "fr_x", "eq")
    E(movw, 1, O)
    E(adds_reg, 0, 0, 1)
    E(ldrh_imm, 1, 0, R_SIG)
    E(movw, 2, SIG)
    E(cmp_reg, 1, 2)
    E(b_cond, "fr_x", "eq")
    E(mov_reg, 4, 0)
    E(movs_imm, 1, 0)
    E(movs_imm, 2, 0)
    a.label("fr_z")
    E(strb_reg, 1, 4, 2)
    E(adds_imm8, 2, 1)
    E(cmp_imm, 2, R_VAL)
    E(b_cond, "fr_z", "lo")
    imm32(1, T["def"])
    E(movs_imm, 2, 0)
    a.label("fr_d")
    E(movs_imm, 3, 15)
    E(ands_reg, 3, 2)
    E(ldrb_reg, 3, 1, 3)
    E(adds_reg, 0, 4, 2)
    E(strb_imm, 3, 0, R_VAL)
    E(adds_imm8, 2, 1)
    E(cmp_imm, 2, NSL * NV)
    E(b_cond, "fr_d", "lo")
    E(movw, 1, SIG)
    E(strh_imm, 1, 4, R_SIG)
    E(mov_reg, 0, 4)
    a.label("fr_x")
    E(pop_list, [4], pc=True)

    # ---- c_fmon(r0 = slot) -> r0 = 1 with FM; clobbers r1-r3
    a.label("c_fmon")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, "c_fmram")
    E(cmp_imm, 0, 0)
    E(b_cond, "fo_x", "eq")
    E(ldrb_imm, 0, 0, R_ON)
    E(lsrs_reg, 0, 4)
    E(movs_imm, 1, 1)
    E(ands_reg, 0, 1)
    a.label("fo_x")
    E(pop_list, [4], pc=True)

    # ---- c_fmv(r0 = slot, r1 = k) -> r0 = its value; c_fmput(r0 = slot, r1 = k, r2 = value): stored, the slot to send; clobber r1-r3
    a.label("c_fmv")
    E(push_list, [4, 5], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(bl, "c_fmram")
    E(cmp_imm, 0, 0)
    E(b_cond, "fv_d", "eq")
    E(lsls_imm, 1, 4, 4)
    E(adds_reg, 0, 0, 1)
    E(adds_reg, 0, 0, 5)
    E(ldrb_imm, 0, 0, R_VAL)
    E(pop_list, [4, 5], pc=True)
    a.label("fv_d")
    imm32(0, T["def"])
    E(ldrb_reg, 0, 0, 5)
    E(pop_list, [4, 5], pc=True)
    a.label("c_fmput")
    E(push_list, [4, 5, 6], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(mov_reg, 6, 2)
    E(bl, "c_fmram")
    E(cmp_imm, 0, 0)
    E(b_cond, "fp_x", "eq")
    E(lsls_imm, 1, 4, 4)
    E(adds_reg, 1, 0, 1)
    E(adds_reg, 1, 1, 5)
    E(strb_imm, 6, 1, R_VAL)
    E(movs_imm, 1, 1)
    E(lsls_reg, 1, 4)
    E(ldrb_imm, 2, 0, R_PEND)
    E(orrs_reg, 2, 1)
    E(strb_imm, 2, 0, R_PEND)
    a.label("fp_x")
    E(pop_list, [4, 5, 6], pc=True)

    # ---- c_fmset(r0 = slot, r1 = 0 / 1): FM off / on (on: its state cleared first); its words to send; clobbers r0-r3
    a.label("c_fmset")
    E(push_list, [4, 5], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(bl, "c_fmram")
    E(cmp_imm, 0, 0)
    E(b_cond, "fs_x", "eq")
    E(movs_imm, 1, 1)
    E(lsls_reg, 1, 4)
    E(ldrb_imm, 2, 0, R_ON)
    E(bics_reg, 2, 1)
    E(cmp_imm, 5, 0)
    E(b_cond, "fs_w", "eq")
    E(orrs_reg, 2, 1)
    E(ldrb_imm, 3, 0, R_CLR)
    E(orrs_reg, 3, 1)
    E(strb_imm, 3, 0, R_CLR)
    a.label("fs_w")
    E(strb_imm, 2, 0, R_ON)
    E(ldrb_imm, 2, 0, R_PEND)
    E(orrs_reg, 2, 1)
    E(strb_imm, 2, 0, R_PEND)
    a.label("fs_x")
    E(pop_list, [4, 5], pc=True)

    if not FM8:
        # ---- c_fmword(r0 = slot, r1 = i) -> r0 = the word, r1 = its X address (fmvoice.words at VEL / NOTE); clobbers r2, r3
        a.label("c_fmword")
        E(push_list, [4, 5, 6, 7], lr=True)
        E(mov_reg, 4, 0)                                                      # r4 = slot
        E(mov_reg, 5, 1)                                                      # r5 = i
        E(bl, "c_fmram")
        E(lsls_imm, 1, 4, 4)
        E(adds_reg, 0, 0, 1)
        E(adds_imm8, 0, R_VAL)
        E(mov_reg, 6, 0)                                                      # r6 = the 16 values
        E(ldrb_imm, 0, 6, V.P_ALG)
        E(lsrs_imm, 0, 0, 3)
        E(movs_imm, 1, 15)
        E(ands_reg, 0, 1)
        E(movs_imm, 1, ALEN)
        E(muls, 0, 1)
        imm32(7, T["alg"])
        E(adds_reg, 7, 7, 0)                                                  # r7 = the algorithm
        imm32(1, F.FB0)
        E(lsls_imm, 0, 4, 7)
        E(adds_reg, 1, 1, 0)
        E(push_list, [1])                                                     # [sp] = the slot's block
        E(cmp_imm, 5, 4 * len(V.PARAMS))
        bc("fw_op", "lo")
        E(subs_imm8, 5, 4 * len(V.PARAMS))
        E(cmp_imm, 5, len(V.GLOBALS))
        bc("fw_key", "hs")
        imm32(0, T["glb"])
        E(ldrb_reg, 0, 0, 5)
        E(ldr_sp, 1, 0)
        E(adds_reg, 1, 1, 0)
        E(str_sp, 1, 0)                                                  # the address
        E(cmp_imm, 5, 0)
        E(b_cond, "fw_g1", "ne")
        E(ldrb_imm, 0, 7, A_FAM)                                              # FLG: 2 for the percussive and bell families
        E(subs_imm8, 0, 1)
        E(movs_imm, 1, 0)
        E(cmp_imm, 0, 1)
        E(b_cond, "fw_g0", "hi")
        E(movs_imm, 1, 2)
        a.label("fw_g0")
        E(mov_reg, 0, 1)
        E(b, "fw_r")
        a.label("fw_g1")
        E(cmp_imm, 5, 1)
        E(b_cond, "fw_g2", "ne")
        E(movs_imm, 0, 0)                                                     # PD: (lev4^2 x gv x 7) >> 2 with the pitch flag
        E(ldrb_imm, 1, 7, A_FLG)
        E(lsls_imm, 1, 1, 31)
        bc("fw_r", "eq")
        E(bl, "fw_gv")
        E(ldrb_imm, 1, 6, V.P_LEV + 3)
        E(muls, 1, 1)
        E(muls, 0, 1)
        E(movs_imm, 1, 7)
        E(muls, 0, 1)
        E(lsrs_imm, 0, 0, 2)
        E(b, "fw_r")
        a.label("fw_g2")
        E(cmp_imm, 5, 2)
        E(b_cond, "fw_g3", "ne")
        E(ldrb_imm, 0, 6, V.P_NZ)                                             # NZ: nz^2 x 255
        E(muls, 0, 0)
        E(movs_imm, 1, 255)
        E(muls, 0, 1)
        E(b, "fw_r")
        a.label("fw_g3")
        E(ldrb_imm, 0, 7, A_FLG)                                              # NOP: the noise operator x FMS
        E(lsrs_imm, 0, 0, 4)
        E(movs_imm, 1, 3)
        E(ands_reg, 0, 1)
        E(movs_imm, 1, F.FMS)
        E(muls, 0, 1)
        E(b, "fw_r")
        a.label("fw_key")                                                     # the key: on / off
        E(ldr_sp, 1, 0)
        E(adds_imm8, 1, F.G_KEY)
        E(str_sp, 1, 0)
        E(mov_reg, 0, 4)
        E(bl, "c_fmon")
        E(cmp_imm, 0, 0)
        bc("fw_r", "eq")
        imm32(0, F.FMKEY)
        E(b, "fw_r")
        # ---- an operator's word: k = i / 11, f = i % 11
        a.label("fw_op")
        E(movs_imm, 0, 0)
        a.label("fw_dv")
        E(cmp_imm, 5, len(V.PARAMS))
        E(b_cond, "fw_dd", "lo")
        E(subs_imm8, 5, len(V.PARAMS))
        E(adds_imm8, 0, 1)
        E(b, "fw_dv")
        a.label("fw_dd")
        E(mov_reg, 4, 0)                                                      # r4 = k (the slot no longer needed but for the address)
        imm32(1, T["par"])
        E(ldrb_reg, 1, 1, 5)
        E(movs_imm, 2, F.FMS)
        E(muls, 2, 0)
        E(adds_reg, 1, 1, 2)
        E(ldr_sp, 2, 0)
        E(adds_reg, 2, 2, 1)
        E(str_sp, 2, 0)                                                  # the address
        for f, lab in enumerate(("R0", "L", "K", "M", "M", "M", "M", "HC", "A", "DH", "DR")):
            if f in (4, 5, 6):
                continue
            E(cmp_imm, 5, f)
            if f == 3:
                E(b_cond, "fw_n3", "lo")
                E(cmp_imm, 5, 6)
                bc("fw_M", "ls")
                a.label("fw_n3")
            else:
                bc(f"fw_{lab}", "eq")
        E(movs_imm, 0, 0)
        E(b, "fw_r")
        # R0 = ((rat x det) >> 12 x fine) >> 12, fine = 4096 + 6 ((step x 171) >> 12)
        a.label("fw_R0")
        E(ldrb_reg, 0, 6, 4)
        E(movs_imm, 1, 24)
        E(muls, 0, 1)                                                         # pos
        E(lsrs_imm, 1, 0, 7)
        E(lsls_imm, 1, 1, 2)
        imm32(2, T["rat"])
        E(raw, h(0x5800 | 1 << 6 | 2 << 3 | 2))                               # ldr r2, [r2, r1]
        E(lsls_imm, 1, 4, 1)
        E(adds_imm8, 1, A_DET)
        E(raw, h(0x5A00 | 1 << 6 | 7 << 3 | 3))                               # ldrh r3, [r7, r1]
        E(raw, umull(1, 3, 2, 3))                                             # r1:r3 = rat x det
        E(lsrs_imm, 1, 1, 12)
        E(lsls_imm, 3, 3, 20)
        E(orrs_reg, 1, 3)
        E(movs_imm, 2, 127)
        E(ands_reg, 0, 2)
        E(movs_imm, 2, 171)
        E(muls, 0, 2)
        E(lsrs_imm, 0, 0, 12)
        E(movs_imm, 2, 6)
        E(muls, 0, 2)
        E(movs_imm, 2, 1)
        E(lsls_imm, 2, 2, 12)
        E(adds_reg, 0, 0, 2)                                                  # fine
        E(raw, umull(1, 3, 1, 0))
        E(lsrs_imm, 1, 1, 12)
        E(lsls_imm, 3, 3, 20)
        E(orrs_reg, 1, 3)
        E(mov_reg, 0, 1)
        E(b, "fw_cl")
        # L = lev^2 x 512 (a modulator: x G >> 8; operator 4 of a pitch algorithm: 0)
        a.label("fw_L")
        E(cmp_imm, 4, 3)
        E(b_cond, "fw_l1", "ne")
        E(movs_imm, 0, 0)
        E(ldrb_imm, 1, 7, A_FLG)
        E(lsls_imm, 1, 1, 31)
        bc("fw_r", "ne")
        a.label("fw_l1")
        E(adds_reg, 0, 6, 4)
        E(ldrb_imm, 0, 0, V.P_LEV)
        E(muls, 0, 0)
        E(lsls_imm, 0, 0, 9)
        E(ldrb_imm, 1, 7, A_CAR)
        E(lsrs_reg, 1, 4)
        E(lsls_imm, 1, 1, 31)
        bc("fw_cl", "ne")
        E(push_list, [0])
        E(bl, "fw_gv")
        E(pop_list, [1])
        E(muls, 0, 1)
        E(lsrs_imm, 0, 0, 8)
        E(b, "fw_cl")
        # K = kw for a carrier
        a.label("fw_K")
        E(movs_imm, 0, 0)
        E(ldrb_imm, 1, 7, A_CAR)
        E(lsrs_reg, 1, 4)
        E(lsls_imm, 1, 1, 31)
        bc("fw_r", "eq")
        E(ldr_imm, 0, 7, A_KW)
        E(b, "fw_r")
        # M_j (j = f - 3): the feedback operator's own = HC; else the routing bit (4 k + j) -> 1
        a.label("fw_M")
        E(subs_imm8, 5, 3)                                                    # j
        E(ldrb_imm, 0, 7, A_FB)
        E(cmp_reg, 0, 4)
        E(b_cond, "fw_m1", "ne")
        E(cmp_reg, 5, 4)
        bc("fw_HC2", "eq")
        a.label("fw_m1")
        E(ldrh_imm, 2, 7, A_MASK)
        E(lsls_imm, 1, 4, 2)
        E(adds_reg, 1, 1, 5)
        E(movs_imm, 0, 0)
        E(lsrs_reg, 2, 1)
        E(lsls_imm, 2, 2, 31)
        bc("fw_r", "eq")
        imm32(0, ONE)
        E(b, "fw_r")
        # HC = fb^2 x 512 for the feedback operator
        a.label("fw_HC")
        E(ldrb_imm, 1, 7, A_FB)
        E(movs_imm, 0, 0)
        E(cmp_reg, 1, 4)
        bc("fw_r", "ne")
        a.label("fw_HC2")
        E(ldrb_imm, 0, 6, V.P_FB)
        E(muls, 0, 0)
        E(lsls_imm, 0, 0, 9)
        E(b, "fw_r")
        # A: v >= 64: atk[(v - 64) >> 1], else ONE
        a.label("fw_A")
        E(adds_reg, 0, 6, 4)
        E(ldrb_imm, 0, 0, V.P_ATK)
        E(subs_imm8, 0, V.CENTRE)
        E(b_cond, "fw_a1", "ge")
        imm32(0, ONE)
        E(b, "fw_r")
        a.label("fw_a1")
        E(lsrs_imm, 0, 0, 1)
        E(lsls_imm, 0, 0, 2)
        imm32(1, T["atk"])
