CTRL = CI.CTRL
SV0, SV_SZ, SV_VT = 0x200490A4, 0xE4, 0x08068294
O_STEPHELD = 0x3C
PS_VT = PM.PS_VT
DP0, DP_SZ, DP_VT = DQ.DP0, DQ.DP_SZ, DQ.DP_VT
NOTE_ON, VOICE_OFF, TICKS, RANDOM = DQ.NOTE_ON, DQ.VOICE_OFF, DQ.GATE_TAB, DQ.RANDOM
ENG = rhrec.ENG
PARAM_GET = CI.PARAM_GET
TRANSPORT, TEMPO, HAL_TICK = CI.TRANSPORT, 0x20012788, 0x20006F3C
NOTE = 0x30
BLK, BLK_LEN = rhrec.OFF["drumarp"]
O_ST, ST_LEN = rhstate.OFF["drumarp"]
MAGIC = 0xD7
PS_PAD_RATE, PS_PAD_ARP, PS_PAD_ORD = 16, 24, 26
ORD_OF_PAD = (4, 5, 0, 1, 2, 3)                          # pads 27-32: fractal, deconstructed, up, down, ping-pong, random
M_UP, M_DOWN, M_PP, M_RND, M_FRAC, M_DEC = 0, 1, 2, 3, 4, 5
KWRAP = 120
COL_ON, COL_OFF = 0x1E, 0x09                             # (Tracks 0x17, 0x02)
# ui (RH52; docs/INTERFAZ.md, the user, 2026-10-28): off / not chosen = the dim of its own colour (dim green), not grey
UI_OFF = 0x1F
UI = False
SEEN_MS = 200
HELD_CLEAR_DUP = (1 << 23) | (1 << 24)
# the running state (RAM)
S_N, S_MAG, S_TRK, S_K, S_FG, S_FP, S_SMP, S_VEL, S_FIRST, S_FL, S_NEXT, S_SEEN, S_BASE = 0, 1, 2, 3, 4, 5, 6, 12, 18, 19, 20, 24, 28
assert S_BASE < ST_LEN and BLK_LEN >= 67
NOTES = False                                            # RH15 (install(notes=True)): the Note view's held notes too
REC = False                                              # RH20 (install(rec=True)): playing with Record, each hit written into the pattern
S_RVAL, S_RVEL = 30, 31                                  # (REC) the last hit's sample / note and velocity
NV0, NV_SZ, NV_VT = 0x2004A604, 0x1B4, 0x08067248        # the tracks' Note views
NV_IDX, O_NMAP, O_NSTEP = 0x0805DFEA, 0x4C, 0x78        # (view, pad) -> the keyboard index; [view + 0x4C] + 8 = index -> note; the step held
S_LAST = 29                                              # (NOTES) the note last played
F_NOTES = 2                                              # (NOTES) S_FL bit 1: the held values are notes (the Note view), not samples
BPM0 = False                                             # RH29 (install(bpm0=True)): the stopped arpeggio's step from p0 of the tempo store
SINGLE = False                                           # RH22 (install(single=True)): one held sample / note arpeggiates too (the user, 2026-10-19:
F_FRESH = 4                                              #   «one note only doesn't trigger it»); S_FL bit 2: the stock just played the first hit
INV = dict(eq="ne", ne="eq", lo="hs", hs="lo", hi="ls", ls="hi", ge="lt", lt="ge", gt="le", le="gt", mi="pl", pl="mi")


def pushw(regs, lr=False): return h(0xE92D) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0))
def popw(regs, lr=False): return h(0xE8BD) + h(sum(1 << r for r in regs) | (1 << 14 if lr else 0))
def mls_(rd, rn, rm, ra): return h(0xFB00 | rn) + h(ra << 12 | rd << 8 | 0x10 | rm)      # rd = ra - rn * rm
def udiv(rd, rn, rm): return h(0xFBB0 | rn) + h(0xF0F0 | rd << 8 | rm)
def ldrh_imm_(rt, rn, imm): return h(0x8800 | (imm // 2) << 6 | rn << 3 | rt)


def arm_code(base, L, prev):
    a = Asm(base)
    E = a.emit
    zc = [0]
    RET = h(0x4770)

    def imm32(rd, v):
        E(movw, rd, v & 0xFFFF)
        E(movt, rd, (v >> 16) & 0xFFFF)

    def bc(target, cond):
        zc[0] += 1
        n = f"_a{zc[0]}"
        E(b_cond, n, INV[cond])
        E(b, target)
        a.label(n)

    t_ord = base
    E(raw, bytes(ORD_OF_PAD) + bytes([PS_PAD_ORD + ORD_OF_PAD.index(m) for m in range(6)]))

    # ---- c_dablk() -> r0 = our block in the tail when valid, else 0; c_daraw() -> r0 = its place (0 without a record); clobber r1-r3
    a.label("c_daraw")
    E(push_list, [4], lr=True)
    E(bl, L["c_rrt"])
    E(cmp_imm, 0, 0)
    E(b_cond, "rw_x", "eq")
    E(adds_imm8, 0, BLK)
    a.label("rw_x")
    E(pop_list, [4], pc=True)
    # c_dasum(r0 = block) -> r1 = its sum (bytes 3..66); clobbers r2, r3
    a.label("c_dasum")
    E(movs_imm, 1, 0x5A)
    E(movs_imm, 3, 3)
    a.label("su_l")
    E(ldrb_reg, 2, 0, 3)
    E(adds_reg, 1, 1, 2)
    E(adds_imm8, 3, 1)
    E(cmp_imm, 3, 67)
    E(b_cond, "su_l", "lo")
    E(movs_imm, 2, 0xFF)
    E(ands_reg, 1, 2)
    E(raw, RET)
    a.label("c_dablk")
    E(push_list, [4], lr=True)
    E(bl, "c_daraw")
    E(cmp_imm, 0, 0)
    E(b_cond, "bk_x", "eq")
    E(mov_reg, 4, 0)
    E(ldrb_imm, 0, 4, 0)
    E(cmp_imm, 0, ord("A"))
    E(b_cond, "bk_0", "ne")
    E(ldrb_imm, 0, 4, 1)
    E(cmp_imm, 0, ord("D"))
    E(b_cond, "bk_0", "ne")
    E(mov_reg, 0, 4)
    E(bl, "c_dasum")
    E(ldrb_imm, 2, 4, 2)
    E(cmp_reg, 1, 2)
    E(b_cond, "bk_0", "ne")
    E(mov_reg, 0, 4)
    E(pop_list, [4], pc=True)
    a.label("bk_0")
    E(movs_imm, 0, 0)
    a.label("bk_x")
    E(pop_list, [4], pc=True)

    # ---- c_dacfg(r0 = track, r1 = pattern) -> r0 = the setting (0 = off); clobbers r1-r3
    a.label("c_dacfg")
    E(push_list, [4], lr=True)
    E(cmp_imm, 0, 7)
    E(b_cond, "cf_0", "hi")
    E(cmp_imm, 1, 7)
    E(b_cond, "cf_0", "hi")
    E(lsls_imm, 4, 0, 3)
    E(adds_reg, 4, 4, 1)
    E(bl, "c_dablk")
    E(cmp_imm, 0, 0)
    E(b_cond, "cf_x", "eq")
    E(adds_reg, 0, 0, 4)
    E(ldrb_imm, 0, 0, 3)
    E(pop_list, [4], pc=True)
    a.label("cf_0")
    E(movs_imm, 0, 0)
    a.label("cf_x")
    E(pop_list, [4], pc=True)

    # ---- c_daset(r0 = track, r1 = pattern, r2 = setting): the block made when missing; clobbers r0-r3
    a.label("c_daset")
    E(push_list, [4, 5, 6], lr=True)
    E(lsls_imm, 4, 0, 3)
    E(adds_reg, 4, 4, 1)
    E(mov_reg, 5, 2)
    E(bl, "c_dablk")
    E(cmp_imm, 0, 0)
    E(b_cond, "st_w", "ne")
    E(bl, "c_daraw")
    E(cmp_imm, 0, 0)
    E(b_cond, "st_x", "eq")
    E(movs_imm, 1, ord("A"))
    E(strb_imm, 1, 0, 0)
    E(movs_imm, 1, ord("D"))
    E(strb_imm, 1, 0, 1)
    E(movs_imm, 1, 0)
    E(movs_imm, 2, 67)
    a.label("st_z")
    E(subs_imm8, 2, 1)
    E(strb_reg, 1, 0, 2)
    E(cmp_imm, 2, 3)
    E(b_cond, "st_z", "hi")
    a.label("st_w")
    E(mov_reg, 6, 0)
    E(adds_reg, 0, 0, 4)
    E(strb_imm, 5, 0, 3)
    E(mov_reg, 0, 6)
    E(bl, "c_dasum")
    E(strb_imm, 1, 6, 2)
    a.label("st_x")
    E(pop_list, [4, 5, 6], pc=True)

    # ---- c_dast() -> r0 = the running state (valid) or 0; c_daini(r0 = track) -> r0 = the state, emptied for it (0: no RAM); clobber r1-r3
    a.label("c_dast")
    E(push_list, [4], lr=True)
    E(bl, L["c_rst"])
    E(cmp_imm, 0, 0)
    E(b_cond, "ds_x", "eq")
    E(adds_imm8, 0, O_ST)
    E(ldrb_imm, 1, 0, S_MAG)
    E(cmp_imm, 1, MAGIC)
    E(b_cond, "ds_x", "eq")
    E(movs_imm, 0, 0)
    a.label("ds_x")
    E(pop_list, [4], pc=True)
    a.label("c_daini")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, L["c_rst"])
    E(cmp_imm, 0, 0)
    E(b_cond, "di_x", "eq")
    E(adds_imm8, 0, O_ST)
    E(movs_imm, 1, 0)
    E(movs_imm, 2, ST_LEN)
    a.label("di_z")
    E(subs_imm8, 2, 1)
    E(strb_reg, 1, 0, 2)
    E(cmp_imm, 2, 0)
    E(b_cond, "di_z", "ne")
    E(movs_imm, 1, MAGIC)
    E(strb_imm, 1, 0, S_MAG)
    E(strb_imm, 4, 0, S_TRK)
    E(movs_imm, 1, 0xFF)
    E(strb_imm, 1, 0, S_FIRST)
    a.label("di_x")
    E(pop_list, [4], pc=True)

    # ---- c_daplr(r0 = track) -> r0 = its player; clobbers r1
    a.label("c_daplr")
    E(movw, 1, DP_SZ)
    E(muls, 0, 1)
    imm32(1, DP0)
    E(adds_reg, 0, 0, 1)
    E(raw, RET)

    # ---- c_dapat(r0 = track) -> r0 = the pattern it plays; clobbers r1-r3
    a.label("c_dapat")
    E(push_list, [4], lr=True)
    E(lsls_imm, 0, 0, 2)
    imm32(1, ENG + 0x30)
    E(adds_reg, 0, 0, 1)
    E(ldr_imm, 0, 0, 0)
    E(movs_imm, 1, 0)
    E(bl, PARAM_GET)
    E(ldrb_imm, 0, 0, 0)
    E(movs_imm, 1, 7)
    E(ands_reg, 0, 1)
    E(pop_list, [4], pc=True)

    # ---- c_datps(r0 = track) -> r0 = its ticks a step (its sync rate); c_dati(r0 = track) -> r0 = the ticks of an arpeggio step; clobber r1-r3
    a.label("c_datps")
    E(push_list, [4], lr=True)
    E(bl, "c_daplr")
    E(ldr_imm, 0, 0, 0x10)
    E(movs_imm, 1, 1)
    E(bl, PARAM_GET)
    E(ldrb_imm, 0, 0, 0)
    E(cmp_imm, 0, 7)
    E(b_cond, "tp_a", "ls")
    E(movs_imm, 0, 3)
    a.label("tp_a")
    E(lsls_imm, 0, 0, 2)
    imm32(1, TICKS)
    E(raw, h(0x5808))                                                     # ldr r0, [r1, r0]
    E(pop_list, [4], pc=True)
    a.label("c_dati")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 0)
    E(bl, "c_dapat")
    E(mov_reg, 1, 0)
    E(mov_reg, 0, 4)
    E(bl, "c_dacfg")
    E(lsrs_imm, 0, 0, 3)
    E(movs_imm, 1, 15)
    E(ands_reg, 0, 1)
    E(cmp_imm, 0, 0)
    E(b_cond, "ti_f", "eq")
    E(cmp_imm, 0, 8)
    E(b_cond, "ti_f", "hi")
    E(subs_imm8, 0, 1)
    E(lsls_imm, 0, 0, 2)
    imm32(1, TICKS)
    E(raw, h(0x5808))                                                     # ldr r0, [r1, r0]
    E(pop_list, [4], pc=True)
    a.label("ti_f")
    E(mov_reg, 0, 4)
    E(bl, "c_datps")
    E(pop_list, [4], pc=True)

    # ---- c_dasmp(r0 = track, r1 = sample): the track's sample through its player (as the stock's sample flip); clobbers r0-r3
    a.label("c_dasmp")
    E(push_list, [4], lr=True)
    E(mov_reg, 4, 1)
    E(bl, "c_daplr")
    E(mov_reg, 2, 4)
    E(ldr_imm, 1, 0, 0x5C)
    E(raw, ldrh_imm_(1, 1, 0x18))
    E(ldr_imm, 0, 0, 0x58)
    E(ldr_imm, 3, 0, 0)
    E(ldr_imm, 3, 3, 0)
    E(raw, h(0x4798))                                                     # blx r3
    E(pop_list, [4], pc=True)

    # ---- c_daoff(r0 = track): its voice of our note released; clobbers r0-r3
    a.label("c_daoff")
    if NOTES:                                                             # (r1 = the note)
        E(push_list, [4, 5], lr=True)
        E(mov_reg, 5, 1)
        E(bl, "c_daplr")
        E(mov_reg, 4, 0)
        E(adds_reg, 0, 0, 5)
    else:
        E(push_list, [4], lr=True)
        E(bl, "c_daplr")
        E(mov_reg, 4, 0)
        E(movs_imm, 1, NOTE)
        E(adds_reg, 0, 0, 1)
    E(ldrb_w, 1, 0, 0xAB)
    E(cmp_imm, 1, 0xFF)
    E(b_cond, "of_x", "eq")
    E(mov_reg, 0, 4)
    E(bl, VOICE_OFF)
    a.label("of_x")
    E(pop_list, [4, 5] if NOTES else [4], pc=True)

    # ---- c_dahit(r0 = track, r1 = velocity): a hit through its player's note-on (its voice released first), as long as an arpeggio step
    a.label("c_dahit")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(sub_sp_imm, 8)
    E(mov_reg, 4, 0)
    E(mov_reg, 6, 1)
    if NOTES:                                                             # (r2 = the note)
        E(mov_reg, 5, 2)
        E(mov_reg, 1, 2)
    E(bl, "c_daoff")
    E(mov_reg, 0, 4)
    E(bl, "c_dati")
    E(mov_reg, 3, 0)                                                      # the gate = an arpeggio step
    E(movs_imm, 0, 0)
    E(str_sp, 0, 0)                                                       # [sp] = no tie
    E(mov_reg, 0, 4)
    E(mov_reg, 7, 3)
    E(bl, "c_daplr")
    if NOTES:
        E(mov_reg, 1, 5)
    else:
        E(movs_imm, 1, NOTE)
    E(mov_reg, 2, 6)
    E(mov_reg, 3, 7)
    E(bl, NOTE_ON)
    E(add_sp_imm, 8)
    E(pop_list, [4, 5, 6, 7], pc=True)

    # ---- c_armod(r0, r1) -> r0 = r0 mod r1 (r1 > 0); clobbers r2
    a.label("c_armod")
    E(raw, udiv(2, 0, 1))
    E(raw, mls_(0, 2, 1, 0))
    E(raw, RET)

    # ---- c_arord(r0 = state, r1 = the order) -> r0 = the place of the next sample; the state moves on (CIRCUIT-HACKS' arp.py)
    a.label("c_arord")
    E(push_list, [4, 5, 6, 7], lr=True)
    E(mov_reg, 4, 0)
    E(mov_reg, 5, 1)
    E(ldrb_imm, 6, 4, S_N)
    E(ldrb_imm, 7, 4, S_K)
    E(cmp_imm, 6, 0)
    bc("or_0", "eq")
    E(cmp_imm, 5, M_FRAC)
    bc("or_fr", "eq")
    E(cmp_imm, 5, M_RND)
    bc("or_rn", "eq")
    E(mov_reg, 0, 7)
    E(mov_reg, 1, 6)
    E(cmp_imm, 5, M_PP)
    E(b_cond, "or_pp", "eq")
    E(bl, "c_armod")                                                      # r0 = k mod n
    E(cmp_imm, 5, M_DOWN)
    E(b_cond, "or_dn", "eq")
    E(cmp_imm, 5, M_DEC)
    bc("or_k", "ne")
    E(mov_reg, 2, 6)                                                      # deconstructed: the even places, then the odd ones
    E(adds_imm8, 2, 1)
    E(lsrs_imm, 2, 2, 1)
    E(cmp_reg, 0, 2)
    E(b_cond, "or_de", "hs")
    E(lsls_imm, 0, 0, 1)
    E(b, "or_k")
    a.label("or_de")
    E(subs_reg, 0, 0, 2)
    E(lsls_imm, 0, 0, 1)
    E(adds_imm8, 0, 1)
    E(b, "or_k")
    a.label("or_dn")
    E(subs_reg, 0, 6, 0)
    E(subs_imm8, 0, 1)
    E(b, "or_k")
    a.label("or_pp")                                                      # ping-pong: 0 .. n-1 .. 1
    E(cmp_imm, 6, 1)
    E(b_cond, "or_0", "ls")
    E(lsls_imm, 1, 6, 1)
    E(subs_imm8, 1, 2)
    E(bl, "c_armod")
    E(cmp_reg, 0, 6)
    E(b_cond, "or_k", "lo")
    E(lsls_imm, 1, 6, 1)
    E(subs_imm8, 1, 2)
    E(subs_reg, 0, 1, 0)
    E(b, "or_k")
    a.label("or_rn")
    E(bl, RANDOM)
    E(lsrs_imm, 0, 0, 4)
    E(mov_reg, 1, 6)
    E(bl, "c_armod")
    E(b, "or_k")
    a.label("or_fr")                                                      # fractal: 0 · 0 1 · 0 1 2 · ...
    E(ldrb_imm, 0, 4, S_FP)
    E(ldrb_imm, 1, 4, S_FG)
    E(cmp_reg, 1, 6)
    E(b_cond, "or_f1", "lo")
    E(movs_imm, 1, 0)
    E(movs_imm, 0, 0)
    a.label("or_f1")
    E(cmp_reg, 0, 1)
    E(b_cond, "or_f2", "ls")
    E(movs_imm, 0, 0)
    a.label("or_f2")
    E(mov_reg, 2, 0)
    E(adds_imm8, 2, 1)
    E(cmp_reg, 2, 1)
    E(b_cond, "or_f3", "ls")
    E(movs_imm, 2, 0)
    E(adds_imm8, 1, 1)
    E(cmp_reg, 1, 6)
    E(b_cond, "or_f3", "lo")
    E(movs_imm, 1, 0)
    a.label("or_f3")
    E(strb_imm, 2, 4, S_FP)
    E(strb_imm, 1, 4, S_FG)
    a.label("or_k")
    E(adds_imm8, 7, 1)
    E(cmp_imm, 7, KWRAP)
    E(b_cond, "or_w", "lo")
    E(movs_imm, 7, 0)
    a.label("or_w")
    E(strb_imm, 7, 4, S_K)
    E(cmp_reg, 0, 6)
    E(b_cond, "or_x", "lo")
    a.label("or_0")
    E(movs_imm, 0, 0)
    a.label("or_x")
