"""The extra automation lanes, 6 bits a step, from a shared pool of the RAM nobody uses (MIT; RH96; docs/DISENO_RH95.md; the user, 2026-11-13:
«Then, implement the maximum amount of extra 6 bit lanes» -> «Per step, shared pool. Apply interpolation during sweeps»).

A lane = one track's destination (one of the matrix's, modmx) over its 8 patterns: 8 x 32 steps x 6 bits = SLOT (192) bytes; a value 0 = nothing
at that step, 1..63 = the 7-bit value * 125 >> 8, + 1 (played back as (v - 1) * 264 of 14 bits).  Pattern p = bytes 24 p .. 24 p + 23.
  * Recording (Record on, a knob whose destination finds no stock lane, and the matrix's extra lane (mxx) taken by another destination): the
    track's lane for that destination, or a free slot of the pool, gets the value at the step that plays (set at its start, the slot 4 head).
  * Playing: at each step's start the track's lanes with a value there are set (modmx's c_mxset, as mxx's); between two steps that both have
    a value (a sweep) the LED frames move the destination in a straight line from the one to the next over the step's length (the time since
    the track's previous step); a lane written at the step that plays holds (no ramp) until the next step.  At most RR_MAX ramping lanes are
    sent a frame (round robin), a change under RAMP_MIN (of 14 bits) is not sent.
  * They follow Clear + a pattern, Clear + a step (and the automation view's), Duplicate of a pattern, Clear + Shift + a knob of the
    Sequenceable page (with mxx's: the track's extra lanes all go).  Not Nudge, the step paste, Mutate, the track copy.
  * Saved with the project in its pack's patch bank (as projsnd; not the internal pack): bank p >> 3 at OFFL + STEPL (p & 7): the data
    (n x 192 at + HEAD), then a HEAD-byte head written last ("L", "N", VER, the check, n, 0, 0, 0, then (track, destination) n times);
    read back after a load (the LED task, core 0 / 1 up) and used only when the check (CHECK0 XOR the table and the data) holds.
The pool (each region gives at most its slots, the ones it has at the boot's first READY frame; the slots in this order):
  * the ITCM 0x100-0x177F and 0x1B98-0x1FFF (the tables went to the flash, RH95), above the heap's limit after the control block CB (up to
    0x2004FD00: the main stack never went below 0x2004FE00, RD39);
  * the ITCM 0x2000-0x337F and 0x3C40-0x3FFF and dspz's staging buffer: an upload of core 0's program writes them (the boot's, before us;
    another only from the factory protocol): the canary at CANARY (dspz's window) tells, and they go, their lanes with them;
  * the backup SRAM (0x40024000): the stock's USB mass storage buffer (Easy Start; Advanced Setup button 9 = bit 17 of the settings' p2).
    RH96 used it while that bit was 1, believing that meant off: **bit 17 = 1 is Easy Start ON** (tools/noes.py): RH96 must not go to the
    device.  With noes (RH97: Easy Start gone) it is always ours (with its clock and DBP on);
  * the bottom of the five task stacks (FreeRTOS: TCB + 0 the saved top, + 48 the stack's base; the stock fills them with 0xA5): Main, UI,
    Storage, Content, IDLE; slots from the base while the 0xA5 run at the first READY frame leaves GUARD bytes above them.  Before a write
    and a region a frame: the guard still 0xA5 and the task's live top (its saved top, or sp when it is the one running) above the slots
    + 64, else the region goes (lanes lost, never a task's frame written).
"""
