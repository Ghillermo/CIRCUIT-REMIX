"""The FM engine of the synth played from the device (MIT; RH70, first part: the values in RAM; the user, 2026-11-04: «Sample mode free pads»,
«11 VA, 12 FM, 13 VA-drum», «Hold the FM pad: pads 17-32», «Hacks' layout, violet» -> 0x47; docs/PORTADO.md «Plan de RH70»).

  * Sample mode (Samples twice) on a synth track, Shift not held: pad 11 = VA (the synth's own engine: FM off), pad 12 = FM on the track's synth
    slot, pad 13 kept for VA-drum (dark); on another sound the three dark and swallowed.  Pad 12 held: pads 17-32 = the 16 starters of
    CIRCUIT-HACKS (their family's colour; the one the slot has now bright), a press loads its 16 values.  Lit: 11 mint / dim, 12 lavender /
    dim (the engine on bright);
  * the Synth page of a track whose slot is FM (the container's knob slot, ahead of synthpage's): K1-K4 the ratios of operators 1-4, K5-K8 their
    levels; Shift + K1-K4 their attack (right of the middle) / percussive decay (left), Shift + K5 the algorithm (8 clicks each), K6 feedback,
    K7 noise, K8 release; a click = 1; Clear + a knob = its default (Hacks' DEFAULTS2).  The page's LEDs lavender, the value as brightness
    (Shift + K1-K4 from the middle), Shift + K5 in its algorithm family's colour;
  * the LED task (core 0 / 1 up: cthresh READY): a slot that changed sends its 49 words to fm0's block (tools/fmvoice.py's words at velocity 100,
    note 60: the operators' R0, L, K, M1-M4, HC, A, DH, DR, then FLG, PD, NZ, NOP, the key last), and when FM goes on first its state words from
    zero; else one word a frame in turn (a lost write mended).
RAM: rhstate OFF2 "fmpage" (clkprobe's room): + 0 the slots with FM (bit s), + 1 to send (bit s), + 2 the round, + 3 pad 12 held (the slot + 1),
+ 4 / + 5 "FM", + 6 to clear first (bit s), + 8 the pads swallowed (bit p), + 12 the 16 values of each slot.
"""
