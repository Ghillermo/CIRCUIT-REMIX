    E(push_list, [4], lr=True)
    E(bl, "c_mxro")
    E(cmp_imm, 0, 0)
    E(b_cond, "rw_x", "ne")
    E(bl, L["c_rrt"])
    E(cmp_imm, 0, 0)
    E(b_cond, "rw_x", "eq")
    E(movw, 1, BLK)
    E(adds_reg, 4, 0, 1)
    E(movs_imm, 1, 0)
