"""Arrhythmia's module host, ABI 3, over SysEx: a proof of concept (MIT; RH67, the user, 2026-11-03: «consider importing Arhytmia modules (the goal is to be able to
develop modules that work on both fw)» -> «SysEx host first»).  Our own code for the interface that Arrhythmia (llcoolkm, MIT) designed and
documents in its docs/user/developers.md and docs/dev/modules-reference.md (https://github.com/llcoolkm/arrhythmia; the modules are its, from its releases): the same module files (.mod), the same host table, the same SysEx
commands for upload and start, so a module built with its tools/build_module.py and sent with its tools/module.py runs on both firmwares.

The host table (TABLE = 0x0806A570, the first 32 bytes of our code area: rhbuild.Build reserves them with OPT modhost, so every module of the
build moves up by 32 bytes): 'CRH1', ABI 3, host_note, 0 (no built-in module), host_note_port, host_param, host_ui, host_midi.

A module ('CRM1' / 'CRM2': magic, size, CRC-32, init / frame / input (/ clock) offsets from 0x400 with bit 0, then the code) lives in ITCM
0x400 .. 0x3FFF; its RAM is ITCM 0x100 .. 0x3FF, zeroed before init.  ITCM is used only while ITCMCR says it is on and at least 16 KB.

SysEx (USB): F0 00 20 29 00 60 cmd .. F7, the stock's manufacturer handler 0x0802CF90 (bl at 0x08026E42 -> c_mhsx); anything else goes to it.
  00            stop the module (the stock display and controls)
  04 a2 a1 a0 (hi lo)..   write bytes at ITCM 0x400 + a (stops a running module; marks ITCM as written this boot)
  05            start: the header and CRC checked, then init; replies 7F.  Refused unless ITCM was written this boot
  0A on         the controls to the module (1, only with an input entry) or back (0); replies 7F
  0B            the clock: <clocked> <running> <pulse> <bpm 2x7> <pulses 5x7> <starts 3x7> <stops 3x7>
  7D a4..a0     32 bytes of ITCM 0x100 .. 0x3FFF (aligned): <addr 5x7> <64 nibbles>; any other address: <addr 5x7> alone
  7F            status: <mode (0 / 3)> <1 | owned << 1> <heap cursor 5x7> <frames 4x7> <module: 0 none, 1 valid, 2 bad, 3 no ITCM>
  Not here (Arrhythmia's): 01-03 light shows, 06 the card picker, 08 DSP reads, 09 the input log, 0C-0F, 10, 7E.  Unknown: swallowed.

Hooks (the stock sites Arrhythmia uses, all still stock in RH65):
  0x0802596E  bl 0x0802960C(frame, src, flag): the LED driver's frame (src + 0 dirty bit, src + 16 the 224 LED bytes) -> c_mhfr: a module
              shown -> frame(leds, n) and the driver gets our buffer; unseen (an input module without the controls) -> frame() runs, the
              stock lights are shown
  0x0802586C  bl 0x0802677A: the Main loop's timer service -> c_mhmain: after it, host_ui's snapshot, STOP, the ring's drain (2 calls a pass)
  0x08033384  bl 0x080333AA(transport): a 24-PPQN pulse on which the sequencer steps -> c_mhpul: START / PULSE to a clock entry
  0x080295CA / D8 / F0 / FC  the input thunks' b.w to 0x08040108 pad (ctx, pad, vel, on) / 0x0804012A button (ctx, code, down) /
              0x08040152 pressure (ctx, pad, value) / 0x0804015E encoder (ctx, knob, delta) -> c_mhpad .. c_mhenc: an owned control goes to
              input(leds, kind, index, value) and not to the stock; its release / pressure follow the press; Shift and the pots always stock;
              Play always to the transport (an owner also sees it); Shift + Sample Rec stops a running module.
Host calls (from the module's entries) only queue (8 entries; a note on, a parameter or a MIDI message needs 3 free, so offs keep room; an off
that does not fit releases its track after what is queued).  The drain: one pitch per track, the router 0x080694B0 (vt[0] on (r, note + 12, vel,
port, 0), vt[1] off (r, note + 12, port, 0); port t = the pads' path, 0x18 + t = the engine only), the parameter set 0x080465DC(group, idx, val),
MIDI out 0x080468FA(7, msg).  Our RAM: rhstate's third block (ram3, ST3, 512 B).
"""
